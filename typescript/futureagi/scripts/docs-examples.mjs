// Turn the TypeScript examples of the generated reference (docs/sdk-reference/*.mdx) into one
// consumer module, so scripts/check-consumer.sh compiles them against the PACKED package the way
// a reader's project would. Every ```typescript fence becomes the body of its own async function
// with `client` declared (nothing runs); the overview's error-import line is kept verbatim, so a
// documented import path that the package does not export fails `tsc` here.
//
//   node scripts/docs-examples.mjs <docs/sdk-reference> <out.mts>
import fs from 'node:fs';
import path from 'node:path';

const [reference, out] = process.argv.slice(2);
if (!reference || !out) {
  console.error('usage: node scripts/docs-examples.mjs <docs/sdk-reference> <out.mts>');
  process.exit(2);
}

// Only fences inside <CodeGroup> are examples a reader copies; the "Signature" expander's
// fences are declarations, not code.
const GROUP = /<CodeGroup>([\s\S]*?)<\/CodeGroup>/g;
const FENCE = /```(?:typescript|ts)[^\n]*\n([\s\S]*?)```/g;
const imports = new Set(['import { Client } from "@future-agi/sdk";']);
const bodies = [];
for (const file of fs.readdirSync(reference).filter((f) => f.endsWith('.mdx')).sort()) {
  const text = [...fs.readFileSync(path.join(reference, file), 'utf-8').matchAll(GROUP)].map((m) => m[1]).join('\n');
  let match;
  let n = 0;
  while ((match = FENCE.exec(text))) {
    const code = match[1].trim();
    if (/^import\s/.test(code)) {
      // Keep documented import lines verbatim, except the client construction example's own.
      for (const line of code.split('\n')) if (/^import\s/.test(line)) imports.add(line);
      continue;
    }
    if (/new Client\(/.test(code)) continue; // the construction example needs real options, not `client`
    bodies.push(`// ${file} #${++n}\nasync function example_${bodies.length + 1}(client: Client) {\n${code.split('\n').map((l) => '  ' + l).join('\n')}\n}\n`);
  }
}
if (bodies.length < 100) {
  console.error(`only ${bodies.length} TypeScript examples found in ${reference}; is this the generated reference?`);
  process.exit(1);
}
fs.writeFileSync(out, `// Generated by scripts/docs-examples.mjs from ${reference}; compiled by check-consumer.sh.\n${[...imports].join('\n')}\n\nexport {};\n\n${bodies.join('\n')}`);
console.log(`docs examples: ${bodies.length} TypeScript examples and ${imports.size} import lines written to ${out}`);
