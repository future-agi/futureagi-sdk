"""The sync-twin generator (``scripts/platform/unasync.py``): its transform rules and its discovery."""

from __future__ import annotations

import importlib.util
from pathlib import Path
from types import ModuleType

REPO = Path(__file__).resolve().parents[3]

ASYNC_SOURCE = '''"""Sandboxes (async)."""

from __future__ import annotations

from collections.abc import AsyncIterator, Awaitable

import httpx

from ._async_client import AsyncSandboxesClient


class AsyncSandbox:
    """A sandbox. Use ``async with`` to kill it on exit."""

    async def __aenter__(self) -> "AsyncSandbox":
        return self

    async def __aexit__(self, *exc: object) -> None:
        await self.kill()

    async def kill(self) -> None:
        # await the delete, then close the stream
        await self._client.request("sandboxes.kill")

    async def lines(self) -> AsyncIterator[str]:
        async with httpx.AsyncClient() as http:
            async for line in http.stream("GET", "x").aiter_lines():
                yield line

    def later(self) -> Awaitable[int]:
        return self._later
'''

SYNC_TWIN = '''# GENERATED by scripts/platform/unasync.py from python/fi/sandboxes/_async_client.py. Do not edit.
"""Sandboxes (sync)."""

from __future__ import annotations

from collections.abc import Iterator

import httpx

from ._client import SandboxesClient


class Sandbox:
    """A sandbox. Use ``with`` to kill it on exit."""

    def __enter__(self) -> "Sandbox":
        return self

    def __exit__(self, *exc: object) -> None:
        self.kill()

    def kill(self) -> None:
        # the delete, then close the stream
        self._client.request("sandboxes.kill")

    def lines(self) -> Iterator[str]:
        with httpx.Client() as http:
            for line in http.stream("GET", "x").iter_lines():
                yield line

    def later(self) -> int:
        return self._later
'''


def _unasync() -> ModuleType:
    spec = importlib.util.spec_from_file_location(
        "platform_unasync", REPO / "scripts" / "platform" / "unasync.py"
    )
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_transform_writes_the_sync_twin() -> None:
    out = _unasync().transform(ASYNC_SOURCE, "python/fi/sandboxes/_async_client.py")
    assert out == SYNC_TWIN
    compile(out, "twin.py", "exec")


def test_transform_is_deterministic_and_idempotent_on_sync_code() -> None:
    unasync = _unasync()
    first = unasync.transform(ASYNC_SOURCE, "x.py")
    assert first == unasync.transform(ASYNC_SOURCE, "x.py")
    body = first.split("\n", 1)[1]
    assert unasync.transform(body, "x.py").split("\n", 1)[1] == body


def test_async_before_an_unknown_token_is_refused() -> None:
    unasync = _unasync()
    try:
        unasync.transform("x = async\n", "bad.py")
    except SystemExit as error:
        assert "has no sync form" in str(error)
    else:
        raise AssertionError("expected SystemExit")


def test_pairs_are_discovered(tmp_path: Path) -> None:
    unasync = _unasync()
    pkg = tmp_path / "fi"
    for rel in (
        "sandboxes/_async_client.py",
        "agents/runs/_async_client.py",
        "gateway/_async_client.py",  # Independently ported data-plane client.
        "gateway/management/_async_client.py",
        "_core/_async/http.py",
        "_core/errors.py",
        "datasets/_async_client.py",
    ):
        (pkg / rel).parent.mkdir(parents=True, exist_ok=True)
        (pkg / rel).write_text("x = 1\n")
    found = [
        (s.relative_to(pkg).as_posix(), t.relative_to(pkg).as_posix())
        for s, t in unasync.pairs(pkg)
    ]
    assert found == [
        ("sandboxes/_async_client.py", "sandboxes/_client.py"),
        ("agents/runs/_async_client.py", "agents/runs/_client.py"),
        ("gateway/management/_async_client.py", "gateway/management/_client.py"),
        ("_core/_async/http.py", "_core/_sync/http.py"),
    ]
