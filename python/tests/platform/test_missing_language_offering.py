"""A valid missing twin passes generation and the actual offering gates together."""
import json
import shutil
from types import SimpleNamespace

import pytest

from ._gates_support import REPO, load
from . import test_contract_offerings as gates


def regenerated_missing_python(monkeypatch, tmp_path):
    generator = gates.module(monkeypatch)
    root = tmp_path / "repo"
    shutil.copytree(REPO / "openapi", root / "openapi")
    path = root / "openapi/platform/wrapper-map.json"
    mapping = json.loads(path.read_text())
    name, entry = next((name, entry) for name, entry in mapping["operations"].items()
                       if entry.get("methods") and len(entry["methods"]) == 1
                       and entry["methods"][0]["py"].startswith("client."))
    wrapper = entry["methods"][0]
    missing_path = wrapper.pop("py")
    wrapper.setdefault("not_offered", {})["py"] = {
        "status": "NOT-OFFERED", "reason": "Python facade not implemented", "owner": "namespace"}
    path.write_text(json.dumps(mapping, indent=2) + "\n")
    checker = load("missing_twin_wrapper_check", "scripts/platform/wrapper_map.py")
    spec = json.loads((root / "openapi/platform/generated/futureagi-platform.openapi.json").read_text())
    assert checker.check(mapping, spec) == []
    generated = generator.generate(root)
    target = root / "tests/fixtures/contracts/operations.json"
    target.parent.mkdir(parents=True)
    target.write_text(json.dumps(generated, indent=2) + "\n")
    for mode in ("py_sync", "py_async"):
        assert "platform:" + name not in generated["public_cases"][mode]
        assert "platform:" + name in {row["id"] for row in generated["not_offered"][mode]}
    # Run the committed inventory, real-client resolution and absence gates against
    # these regenerated bytes, rather than only testing the scheduler in isolation.
    monkeypatch.setattr(gates, "REPO", root)
    monkeypatch.setattr(gates, "module", lambda _: SimpleNamespace(generate=lambda: generator.generate(root)))
    return generated, missing_path


def test_regenerated_missing_python_twin_passes_complete_offering_gate(monkeypatch, tmp_path):
    regenerated_missing_python(monkeypatch, tmp_path)
    gates.test_committed_inputs_and_language_inventories(monkeypatch)
    gates.test_every_scheduled_method_resolves_on_real_root_clients(monkeypatch)
    gates.test_unavailable_declarations_do_not_hide_registered_python_methods(monkeypatch)
    gates.test_management_availability_is_explicit_and_public(monkeypatch)


@pytest.mark.parametrize("mode", ["sync", "async"])
def test_missing_python_path_cannot_conceal_a_registered_method(monkeypatch, tmp_path, mode):
    from fi import AsyncFutureAGIClient, FutureAGIClient
    _, path = regenerated_missing_python(monkeypatch, tmp_path)
    parts = path.split(".")[1:]
    target = lambda: None
    for part in reversed(parts[1:]):
        target = SimpleNamespace(**{part: target})
    cls = AsyncFutureAGIClient if mode == "async" else FutureAGIClient
    monkeypatch.setattr(cls, parts[0], property(lambda _: target), raising=False)
    with pytest.raises(pytest.fail.Exception, match="DID NOT RAISE"):
        gates.test_unavailable_declarations_do_not_hide_registered_python_methods(monkeypatch)
