"""Write ``fixtures/census-fi-evals.json``: every ``fi.evals`` import in the published docs, the site
and the snippets the app shows.

    python -I python/tests/evals/tools/census.py OUT.json docs=REPO@COMMIT site=REPO@COMMIT app=REPO@COMMIT

Each source is read at its commit with ``git grep`` and ``git show`` (read-only: no checkout, no
fetch). For every ``from fi.evals[.sub] import NAME`` the fixture counts the import lines per source,
and it counts the shell lines that run the retired ``fi`` console script. ``record_upstream.py``
then records whether each name imports in ai-evaluation 1.1.0, and ``test_surface.py`` checks that
each name that does also imports here.
"""

import collections
import json
import os
from pathlib import Path
import re
import subprocess
import sys

# Pages and examples only: generated reference data (JSON) is not an example someone copies.
FILES = ("*.md", "*.mdx", "*.py", "*.ipynb", "*.astro", "*.html", "*.txt", "*.rst", "*.ts", "*.tsx", "*.js", "*.mjs")
PATTERNS = ("fi.evals", "ai-evaluation", "fi run", "fi init", "fi list", "fi validate", "fi view", "fi export", "fi config")
IMPORT = re.compile(r"(?<![\w.])from\s+(fi\.evals(?:\.[A-Za-z_]\w*)*)\s+import\s+")
CLI = re.compile(r"^\s*(?:\$\s*)?fi\s+(run|init|list|validate|view|export|config)\b", re.M)
NAME = re.compile(r"[A-Za-z_]\w*|\*")
LINES = re.compile(r"\n|\\n")


def imported_names(rest):
    """The names of one import statement, given the text after ``import``: a parenthesised list
    (comments dropped, up to the closing parenthesis) or the rest of the line (up to a comment, a
    backtick or a semicolon). A backslash continuation is followed. In a notebook a line also ends
    at an escaped newline (a backslash followed by n)."""
    if rest.startswith("("):
        parts = []
        for line in LINES.split(rest[1:]):
            code = line.split("#", 1)[0]
            if ")" in code:
                parts.append(code.split(")", 1)[0])
                break
            parts.append(code)
        text = ",".join(parts)
    else:
        text = ""
        for line in LINES.split(rest):
            code = re.split(r"[#`;]", line, maxsplit=1)[0]
            if code.rstrip().endswith("\\"):
                text += code.rstrip()[:-1] + ","
                continue
            text += code
            break
    names = []
    for part in text.split(","):
        name = part.strip().split(" as ")[0].strip()
        if NAME.fullmatch(name):
            names.append(name)
    return names


def _git(repo, *args):
    result = subprocess.run(["git", "-C", repo, *args], capture_output=True, text=True, errors="replace")
    if result.returncode and not (args[0] == "grep" and result.returncode == 1):
        raise RuntimeError(result.stderr.strip())
    return result.stdout


def scan(repo, rev):
    grep = ["grep", "-l", "-F"] + [x for p in PATTERNS for x in ("-e", p)] + [rev, "--", *FILES]
    files = sorted(set(_git(repo, *grep).split()))
    symbols, cli, hits = collections.Counter(), collections.Counter(), 0
    for blob in files:
        text = _git(repo, "show", blob)
        found = False
        for match in IMPORT.finditer(text):
            for name in imported_names(text[match.end():]):
                symbols[f"{match.group(1)}:{name}"] += 1
                found = True
        for match in CLI.finditer(text):
            cli[match.group(1)] += 1
            found = True
        hits += found
    return {"files_with_hits": hits, "symbols": symbols, "cli": dict(cli)}


def main(argv):
    if len(argv) < 3:
        print(__doc__, file=sys.stderr)
        return 2
    sources, table, provenance = {}, {}, {}
    private_path = os.environ.get("CENSUS_PRIVATE_PROVENANCE")
    if private_path and Path(__file__).resolve().parents[4] in Path(private_path).resolve().parents:
        raise ValueError("revision-bound provenance must be outside the repository")
    for spec in argv[2:]:
        label, _, where = spec.partition("=")
        repo, _, rev = where.rpartition("@")
        result = scan(repo, rev)
        provenance[label] = {"repository": repo, "revision": rev}
        remote = _git(repo, "remote", "get-url", "origin").strip().rstrip("/").removesuffix(".git")
        sources[label] = {"repository": "/".join(remote.split("/")[-2:]), "files_with_hits": result["files_with_hits"], "cli_lines": result["cli"]}
        for key, count in result["symbols"].items():
            table.setdefault(key, {name: 0 for name in [s.partition("=")[0] for s in argv[2:]]})[label] = count
    out = {
        "note": ("Every `from fi.evals... import NAME` in the docs, website and app input snapshots, "
                 "with the number of import lines in each. Revision-bound provenance is kept outside this repository. Generated by tests/evals/tools/census.py."),
        "sources": sources,
        "symbols": dict(sorted(table.items())),
    }
    with open(argv[1], "w") as fh:
        json.dump(out, fh, indent=1)
        fh.write("\n")
    if private_path:
        Path(private_path).write_text(json.dumps(provenance, indent=2) + "\n")
    print(f"{len(table)} names")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
