#!/usr/bin/env node
/** Generate connector facades and their policy tables from pinned contract slices. */
import { readFileSync, writeFileSync, mkdirSync, existsSync, unlinkSync } from "node:fs";
import { createHash } from "node:crypto";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { buildPolicy } from "../platform/policy-model.mjs";
import { pyLiteral, pyOperation } from "../platform/emit-policy.mjs";
import { tsEntry } from "../platform/policy-shape.mjs";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const read = (p) => JSON.parse(readFileSync(path.join(root, p), "utf8"));
const source = read("openapi/connectors/source.json");
const features = read("openapi/connectors/features.json");
const paginationRows = read("openapi/sdk/pagination-dialects.json").operations;
const paginationNote = (row) => paginationRows.find((p) => p.method === row.method && p.path === row.path)?.documentation ?? "";
for (const pin of Object.values(source)) {
  const keys = new Set(["source_label", "source_digest", "slice", "slice_sha256"]);
  if (Object.keys(pin).some((key) => !keys.has(key)) || !/^sha256:[a-f0-9]{64}$/.test(pin.source_digest ?? "") ||
      !["enterprise customer contract", "customer connector contract"].includes(pin.source_label)) {
    throw new Error("Connector source provenance must contain only content digests and neutral labels");
  }
  const digest = createHash("sha256").update(readFileSync(path.join(root, pin.slice))).digest("hex");
  if (digest !== pin.slice_sha256) throw new Error("Pinned connector contract digest differs");
}
const ee = read(source.ee.slice), fa = read(source.fa.slice);
const camel = (s) => s.replace(/_([a-z])/g, (_, c) => c.toUpperCase());
const snake = (s) => s.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toLowerCase();
const banner = "Generated by scripts/connectors/generate.mjs. Do not edit.";
// Entries name operations, never routes. Path, body and query facts come from the contract.
const names = {
  "connectors.catalog": ["connectors", "catalog", "mcp_core"],
  "connectors.addCustomMcp": ["connectors", "add_custom_mcp", "mcp_core"],
  "connectors.get": ["connectors", "get", "mcp_core"],
  "connectors.disconnect": ["connectors", "delete", "mcp_core"],
  "connectors.refreshTools": ["connectors", "refresh_tools", "mcp_core"],
  "connectors.attach": ["connectors", "attach", "mcp_core"],
  "connectors.detach": ["connectors", "detach", "mcp_core"],
  "connectors.connect": ["connectors", "connect_app", "oauth_connect"],
  "platform.credentials.list": ["credentials", "list", "credential_reads"],
  "platform.credentials.get": ["credentials", "get", "credential_reads"],
  "platform.credentials.bindings": ["credentials", "bindings", "credential_reads"],
  "integrations_connections_list": ["integrations", "list", "data_integrations"],
  "integrations_connections_create": ["integrations", "create", "data_integrations"],
  "integrations_connections_read": ["integrations", "get", "data_integrations"],
  "integrations_connections_partial_update": ["integrations", "update", "data_integrations"],
  "integrations_connections_update": ["integrations", "replace", "data_integrations"],
  "integrations_connections_delete": ["integrations", "delete", "data_integrations"],
  "integrations_connections_validate_credentials": ["integrations", "validate", "data_integrations"],
  "integrations_connections_pause": ["integrations", "pause", "data_integrations"],
  "integrations_connections_resume": ["integrations", "resume", "data_integrations"],
  "integrations_connections_sync_now": ["integrations", "sync_now", "data_integrations"],
  "integrations_connections_slack_channels_list": ["integrations", "slack_channels", "slack_channels"],
  "integrations_sync-logs_list": ["integrations.sync_logs", "list", "data_integrations"],
  "integrations_sync-logs_read": ["integrations.sync_logs", "get", "data_integrations"],
};
const active = (feature) => features[feature] &&
  (feature !== "oauth_connect" || features.mcp_core) &&
  (feature !== "slack_channels" || features.data_integrations);
const eeOps = buildPolicy(ee).operations;
const rows = eeOps.filter((o) => names[o.name]).map((o) => ({ ...o, origin: "ee" }));
for (const [route, item] of Object.entries(fa.paths)) {
  for (const method of ["get", "post", "put", "patch", "delete"]) {
    const op = item[method];
    if (!op || !names[op.operationId]) continue;
    const params = [...(item.parameters ?? []), ...(op.parameters ?? [])];
    const body = params.some((p) => p.in === "body") ? "json" : "none";
    const row = {name: op.operationId, operation_id: op.operationId, origin: "fa",
      path: (fa.basePath === "/" ? "" : fa.basePath ?? "") + route, method: method.toUpperCase(),
      path_params: [...route.matchAll(/\{([^}]+)\}/g)].map((m) => m[1]),
      query: params.filter((p) => p.in === "query").map((p) => p.name), body};
    rows.push(row);
  }
}
const outputs = new Map();
const put = (p, text) => {
  if ((p.endsWith(".py") || p.endsWith(".ts")) && text.split("\n").length > 400) throw new Error(`module too long: ${p}`);
  outputs.set(p, text + "\n");
};
const pyBase = "python/fi", tsBase = "typescript/futureagi/src";
const mapping = {};
for (const row of rows) {
  const [ns, method, feature] = names[row.name];
  const args = row.path_params.map((p) => p === "id" ? (ns.endsWith("sync_logs") ? "log_id" : "connection_id") : snake(p));
  row.args = args; row.ns = ns; row.public_method = method; row.feature = feature;
  const kw = row.query.map(snake);
  if (row.body === "json" && !["pause", "resume", "sync_now", "refresh_tools"].includes(method)) args.push("body");
  const serverMethod = row.origin === "ee" ? row.name.split(".").slice(1).join(".") : row.operation_id;
  const publicTail = `${ns}.${method}`.split(".").slice(-serverMethod.split(".").length).join(".");
  mapping[row.name] = { operation_id: row.operation_id, source: row.origin, feature,
    ...(snake(serverMethod) === publicTail ? {} : {rename: {from: serverMethod, to: publicTail, why: "Use the public namespace vocabulary"}}),
    ...(active(feature) ? {methods: [{py: `client.${ns}.${method}`, ts: `client.${ns.split(".").map(camel).join(".")}.${camel(method)}`,
      py_args: [...args, ...(kw.length ? ["*", ...kw] : [])], ts_args: [...args.map(camel), ...kw.map((k) => `options.${camel(k)}`)]}]} :
      {unwrapped: "Feature is absent from this artifact", until: "if-needed",
        languages: {py: "NOT-OFFERED", ts: "NOT-OFFERED"}}) };
}
for (const op of eeOps.filter((o) => !names[o.name])) mapping[op.name] = {
  unwrapped: op.human_only ? "Human-only credential mutation in the Console" : "OAuth completion requires the browser",
  until: "never", languages: {py: "NOT-OFFERED", ts: "NOT-OFFERED"}};
mapping.integrations_slack_install_create = {unwrapped: "Browser OAuth installation", until: "never", languages: {py: "NOT-OFFERED", ts: "NOT-OFFERED"}};
put("openapi/connectors/wrapper-map.json", JSON.stringify({sources: source, operations: mapping}, null, 2));
// Shared consumers must see the same OFF disposition as the supplemental map.
// Preserve unrelated entries and the shared contract's response/schema metadata.
const sharedMap = read("openapi/platform/wrapper-map.json");
for (const [name, row] of Object.entries(mapping)) {
  const previous = sharedMap.operations[name];
  if (!row.feature || !previous) continue;
  const {methods, unwrapped, until, languages, ...metadata} = previous;
  if (!active(row.feature)) {
    sharedMap.operations[name] = {...metadata, unwrapped: row.unwrapped, until: row.until, languages: row.languages};
  } else if (unwrapped === "Feature is absent from this artifact") {
    sharedMap.operations[name] = {...metadata, methods: row.methods.map((m) => ({...m, handle: null}))};
  }
}
put("openapi/platform/wrapper-map.json", JSON.stringify(sharedMap, null, 2));
// One table per independently removable feature.
for (const feature of Object.keys(features)) {
  const ops = rows.filter((r) => r.feature === feature && active(feature));
  if (!ops.length) continue;
  const py = [`# ${banner}`, "from fi._core.policy import OperationSpec as Op, PaginationSpec as Page, StreamSpec as Stream", "", "OPERATIONS = {"];
  const ts = [`// ${banner}`, 'import type { OperationTable } from "../../../_core/policy";', 'import type { CatalogOperation } from "../../../_core/catalog";', "export const OPERATIONS = {"];
  for (const row of ops) {
    if (row.origin === "ee") {
      py.push(`    ${JSON.stringify(row.name)}: ${pyOperation(row)},`);
      ts.push(`  ${JSON.stringify(row.name)}: ${JSON.stringify(tsEntry(row))},`);
    } else {
      const spec = {name: row.name, family: "integrations", method: row.method, path: row.path,
        path_params: row.path_params, query: row.query, body: row.body, operation_id: row.operation_id};
      const pagination = ["integrations_connections_list", "integrations_sync-logs_list"].includes(row.name) ? {
        page_param: "page_number", size_param: "page_size", first_page: 0,
        items: row.name === "integrations_connections_list" ? "connections" : "sync_logs", total_items: "metadata.total_count"} : null;
      py.push(`    ${JSON.stringify(row.name)}: (Op(**${pyLiteral(spec)}), "result", ${pyLiteral(pagination)}),`);
      ts.push(`  ${JSON.stringify(row.name)}: ${JSON.stringify({id: row.name, public: row.name, method: row.method,
        path: row.path, path_params: row.path_params, query: row.query, operation_id: row.operation_id, unwrap: "result", pagination})},`);
    }
  }
  py.push("}");
  ts.push(`} satisfies ${ops[0].origin === "ee" ? "OperationTable" : "Record<string, CatalogOperation>"};`);
  put(`${pyBase}/generated/platform/connectors/${feature}.py`, py.join("\n"));
  put(`${tsBase}/generated/connectors/${feature}.ts`, ts.join("\n").replaceAll("../../../_core", "../../_core"));
}
put(`${pyBase}/generated/platform/connectors/__init__.py`, `# ${banner}\n"""Generated connector operation tables."""`);
const eeFeatures = ["mcp_core", "oauth_connect", "credential_reads"].filter(active);
put(`${pyBase}/_core/connector_policy.py`, [`# ${banner}`, ...eeFeatures.map((f) => `from fi.generated.platform.connectors.${f} import OPERATIONS as ${f.toUpperCase()}`),
  `OPERATIONS = {${eeFeatures.map((f) => `**${f.toUpperCase()}`).join(", ")}}`].join("\n"));
put(`${tsBase}/_core/connector-policy.ts`, [`// ${banner}`, ...eeFeatures.map((f) => `import { OPERATIONS as ${f.toUpperCase()} } from "../generated/connectors/${f}";`),
  `export const CONNECTOR_OPERATIONS = {${eeFeatures.map((f) => `...${f.toUpperCase()}`).join(", ")}};`].join("\n"));
const classes = {connectors: "Connectors", credentials: "Credentials", integrations: "Integrations", "integrations.sync_logs": "SyncLogs"};
for (const family of ["connectors", "credentials", "integrations"]) {
  const own = rows.filter((r) => r.ns.split(".")[0] === family && active(r.feature));
  if (!own.length) continue;
  const isFA = family === "integrations", usedFeatures = [...new Set(own.map((r) => r.feature))];
  const py = [`# ${banner}`, `"""${classes[family]} on FutureAGIClient; no provider or browser calls are made by the SDK."""`,
    "from typing import Any, Mapping", `from fi._core.${isFA ? "catalog" : "connector_resource"} import Resource, AsyncResource`,
    "from fi._core.pagination import list_page, alist_page", "from fi._core.connector_resource import cursor_page, async_cursor_page",
    ...usedFeatures.map((f) => `from fi.generated.platform.connectors.${f} import OPERATIONS as ${f.toUpperCase()}`), ""];
  const ts = [`// ${banner}`, `import { Resource } from "../_core/${isFA ? "catalog" : "connector-resource"}";`,
    'import { listPage } from "../_core/pagination";', 'import { cursorPage } from "../_core/connector-resource";',
    ...usedFeatures.map((f) => `import { OPERATIONS as ${f.toUpperCase()} } from "../generated/connectors/${f}";`), ""];
  for (const ns of Object.keys(classes).filter((n) => n.split(".")[0] === family).reverse()) {
    const nsRows = own.filter((r) => r.ns === ns);
    for (const async of [true, false]) {
      py.push(`class ${async ? "Async" : ""}${classes[ns]}(${async ? "Async" : ""}Resource):`, `    """${classes[ns]} operations using the root client's transport."""`);
      if (ns === "integrations") py.push("    @property", `    def sync_logs(self) -> "${async ? "Async" : ""}SyncLogs":`,
        '        """Read sync history for data connections."""', `        return ${async ? "Async" : ""}SyncLogs(self._client)`, "");
      for (const r of nsRows) {
        const autoBody = r.body === "json" && !r.args.includes("body");
        const args = r.args.map((a) => a === "body" ? "body: Mapping[str, Any] | None = None" : `${a}: str`);
        if (r.query.length) args.push("*", ...r.query.map((q) => `${snake(q)}: ${q.includes("page") || q === "limit" ? "int" : "str"} | None = None`));
        const pathArgs = `{${r.path_params.map((p, i) => `${JSON.stringify(p)}: ${r.args[i]}`).join(", ")}}`;
        const queryArgs = `{${r.query.map((q) => `${JSON.stringify(q)}: ${snake(q)}`).join(", ")}}`;
        const body = r.body === "json" ? (autoBody ? "{}" : "body") : "None";
        const note = r.public_method === "connect_app" ? "Return the sign-in URL; never follow it or complete OAuth." :
          r.ns === "credentials" ? "Read credential metadata only, never secret values." : `${r.public_method.replaceAll("_", " ")} using the declared server operation.`;
        py.push(`    ${async ? "async " : ""}def ${r.public_method}(self${args.length ? ", " + args.join(", ") : ""}) -> Any:`, `        """${note}${paginationNote(r) ? " " + paginationNote(r) : ""}"""`);
        const key = `${r.feature.toUpperCase()}[${JSON.stringify(r.name)}]`;
        const query = `query={k: v for k, v in ${queryArgs}.items() if v is not None}`;
        if (r.name === "platform.credentials.list") py.push(`        return ${async ? "await alist_page" : "list_page"}(self._client._platform, ${JSON.stringify(r.name)})`);
        else if (r.public_method === "slack_channels") py.push(`        return ${async ? "await async_cursor_page" : "cursor_page"}(self, ${key}, path=${pathArgs}, ${query})`);
        else if (r.public_method === "connect_app") {
          py.push(`        result = ${async ? "await " : ""}self._client._platform.call(${JSON.stringify(r.name)}, path=${pathArgs}, body=body)`, '        return result["authorizeUrl"]');
        } else if (isFA) py.push(`        return ${async ? "await " : ""}self._call(${key}, path=${pathArgs}, ${query}, body=${body})`);
        else py.push(`        return ${async ? "await " : ""}self._client._platform.call(${JSON.stringify(r.name)}, path=${pathArgs}, ${query}, body=${body})`);
        py.push("");
      }
    }
    ts.push(`/** ${classes[ns]} operations using the root client's configured transport. */`, `export class ${classes[ns]} extends Resource {`);
    if (ns === "integrations") ts.push("  /** Read synchronization history for data connections. */", "  get syncLogs(): SyncLogs { return new SyncLogs(this.client, this.headers); }");
    for (const r of nsRows) {
      const args = r.args.map((a) => a === "body" ? "body?: Record<string, unknown>" : `${camel(a)}: string`);
      if (r.query.length) args.push(`options: {${r.query.map((q) => `${camel(q)}?: ${q.includes("page") || q === "limit" ? "number" : "string"}`).join("; ")}} = {}`);
      const pathArgs = `{${r.path_params.map((p, i) => `${JSON.stringify(p)}: ${camel(r.args[i])}`).join(", ")}}`;
      const query = `{${r.query.map((q) => `${JSON.stringify(q)}: options.${camel(q)}`).join(", ")}}`;
      const body = r.body === "json" ? (r.args.includes("body") ? "body" : "{}") : "undefined";
      const key = `${r.feature.toUpperCase()}[${JSON.stringify(r.name)}]`;
      ts.push(`  /** ${r.public_method === "connect_app" ? "Return the sign-in URL without following it or completing OAuth." : "Uses the declared server operation and the root client transport."}${paginationNote(r) ? " " + paginationNote(r) : ""} */`,
        `  ${r.public_method === "connect_app" ? "async " : ""}${camel(r.public_method)}(${args.join(", ")}) {`);
      if (r.name === "platform.credentials.list") ts.push(`    return listPage(this.client._platform, ${JSON.stringify(r.name)});`);
      else if (r.public_method === "slack_channels") ts.push(`    return cursorPage((q) => this.call(${key}, ${pathArgs}, q, undefined), ${query});`);
      else if (r.public_method === "connect_app") ts.push(`    const result = await this.client._platform.call<{authorizeUrl: string}>(${JSON.stringify(r.name)}, {path: ${pathArgs}, body});`, "    return result.authorizeUrl;");
      else if (isFA) ts.push(`    return this.call(${key}, ${pathArgs}, ${query}, ${body});`);
      else ts.push(`    return this.client._platform.call(${JSON.stringify(r.name)}, {path: ${pathArgs}, query: ${query}, body: ${body}});`);
      ts.push("  }");
    }
    ts.push("}");
  }
  put(`${pyBase}/${family}/__init__.py`, py.join("\n").trimEnd());
  put(`${tsBase}/${family}/index.ts`, ts.join("\n"));
}
const managed = [
  ...Object.keys(features).flatMap((f) => [`${pyBase}/generated/platform/connectors/${f}.py`, `${tsBase}/generated/connectors/${f}.ts`]),
  ...["connectors", "credentials", "integrations"].flatMap((n) => [`${pyBase}/${n}/__init__.py`, `${tsBase}/${n}/index.ts`]),
];
const check = process.argv.includes("--check");
const outIndex = process.argv.indexOf("--out");
if (outIndex !== -1 && !process.argv[outIndex + 1]) throw new Error("--out requires a directory");
const destination = outIndex === -1 ? root : path.resolve(process.argv[outIndex + 1]);
for (const rel of managed.filter((p) => !outputs.has(p))) {
  if (!existsSync(path.join(destination, rel))) continue;
  if (check) throw new Error(`Hidden file still exists: ${rel}`);
  unlinkSync(path.join(destination, rel));
}
for (const [rel, text] of outputs) {
  const file = path.join(destination, rel);
  if (check) {
    if (!existsSync(file) || readFileSync(file, "utf8") !== text) throw new Error(`Generated file differs: ${rel}`);
  } else { mkdirSync(path.dirname(file), {recursive: true}); writeFileSync(file, text); }
}
