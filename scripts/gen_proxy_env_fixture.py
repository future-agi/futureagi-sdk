class _Env:
    """``os.environ`` reads as ``env`` inside the block: the standard library and the routers read it there."""

    def __init__(self, env):
        self.env = dict(env)

    def __enter__(self):
        self.saved = os.environ
        os.environ = self.env
        return self

    def __exit__(self, *exc):
        os.environ = self.saved


def _host_text(url: str) -> str:
    """The host string the oracle hands CPython: IDNA lower-case host (brackets for IPv6, trailing dot kept),
    ``:port`` with the digits as written when the URL has one."""
    netloc = urlsplit(url).netloc.rsplit("@", 1)[-1]
    if netloc.startswith("["):
        host, _, rest = netloc[1:].partition("]")
        host, port = f"[{host.lower()}]", rest[1:] if rest.startswith(":") else ""
    else:
        host, _, port = netloc.partition(":")
        host = host.lower().encode("idna").decode("ascii") if host.isascii() else host.encode("idna").decode("ascii").lower()
    return host + (":" + port if port.isascii() and port.isdigit() else "")


def cpython_proxied(url: str, env: dict) -> bool:
    if not any(name.lower() in ("http_proxy", "all_proxy") and value for name, value in env.items()):
        return False
    with _Env(env):
        return not proxy_bypass_environment(_host_text(url), getproxies_environment())


def libraries_proxied(url: str, env: dict) -> bool:
    import httpx
    from requests.utils import get_environ_proxies, select_proxy

    if not any(name.lower() in ("http_proxy", "all_proxy") and value for name, value in env.items()):
        return False
    with _Env(env):
        try:
            with httpx.Client(trust_env=True) as client:
                if client._transport_for_url(httpx.URL(url)) is not client._transport:
                    return True
            return bool(select_proxy(url, get_environ_proxies(url)))
        except Exception:
            return True  # a router that cannot answer (httpx rejects some NO_PROXY entries) counts as routing


def _loopback(host: str) -> bool:
    name = host.strip("[]").lower()
    if name == "localhost":
        return True
    try:
        address = ipaddress.ip_address(name)
    except ValueError:
        return False
    if address.version == 4:
        return address in ipaddress.ip_network("127.0.0.0/8")
    return address == ipaddress.IPv6Address("::1")


def _host_shape(url: str):
    """The reason a plain-HTTP URL's host is not the one every reader finds, else None."""
    rest = re.sub(r"^[A-Za-z][A-Za-z0-9+.-]*://", "", url)
    authority = re.split(r"[/?#]", rest, maxsplit=1)[0]
    host = authority.rsplit("@", 1)[-1]
    host = host[: host.rfind(":")] if re.search(r":[0-9]*$", host) and not host.endswith("]") else host
    if host == "":
        return "empty"
    if "\\" in authority or "%5c" in authority.lower():
        return "backslash"
    if "@" in authority and re.search(r"[\[\]]|%5[bd]", authority.rsplit("@", 1)[0], re.IGNORECASE):
        return "bracket-in-userinfo"
    if "@" in authority:
        return "userinfo"
    if not url.lower().startswith("https:") and "@" in rest[len(authority):]:
        return "at-after-host"
    return None


def decide(url: str, env: dict, allow, caller: bool, proxied) -> tuple:
    scheme = url.split(":", 1)[0].lower()
    if scheme not in ("http", "https"):
        return True, "not_plain_http"
    if _host_shape(url) is not None:
        return False, "ambiguous_host"
    if scheme != "http":
        return True, "not_plain_http"
    host = urlsplit(url).hostname or ""
    if _loopback(host.encode("ascii", "replace").decode() if host.isascii() else host):
        # a request the caller's own proxy carries is not direct, loopback or not
        return (False, "caller_proxy") if caller else (True, "loopback")
    zone = host.rstrip(".").lower()
    if zone == "futureagi.com" or zone.endswith(".futureagi.com"):
        return False, "future_agi_host"
    opted = bool(allow) if allow is not None else env.get("FI_ALLOW_INSECURE_HTTP") == "1"
    if not opted:
        return False, "not_opted_in"
    if proxied(url, env):
        return False, "env_proxy"
    if caller:
        return False, "caller_proxy"
    return True, "opted_in"


def _union(url: str, env: dict) -> bool:
    return cpython_proxied(url, env) or libraries_proxied(url, env)


def channel_port(url: str) -> dict:
    netloc = urlsplit(url).netloc
    port = netloc.rsplit(":", 1)[1] if re.search(r":[^\]]*$", netloc) and not netloc.endswith("]") else None
    if port is None:
        return {"url": url, "refused": False, "port": None}
    ok = re.fullmatch(r"[0-9]{1,5}", port) is not None and 1 <= int(port) <= 65535
    return {"url": url, "refused": not ok, "port": int(port) if ok else None}


def build() -> dict:
    env_rows, library_env_rows = [], []
    for row_id, env, url in ENV_INPUTS:
        shared = cpython_proxied(url, env)
        if _union(url, env) == shared:
            env_rows.append({"id": row_id, "env": env, "url": url, "proxied": shared})
        else:
            library_env_rows.append({"id": row_id, "env": env, "url": url, "proxied": shared, "libraryProxied": True})
    decisions, library_decisions = [], []
    for url in DECISION_URLS:
        for opt_id, allow, text in OPT_INS:
            for env_id, base in ENVS:
                env = dict(base) if text is None else {"FI_ALLOW_INSECURE_HTTP": text, **base}
                for caller in (False, True):
                    row_id = f"{url}|{opt_id}|{env_id}|{'caller' if caller else 'direct'}"
                    shared = decide(url, env, allow, caller, cpython_proxied)
                    both = decide(url, env, allow, caller, _union)
                    row = {"id": row_id, "url": url, "env": env, "allowInsecureHttp": allow, "callerProxied": caller}
                    if shared == both:
                        decisions.append({**row, "allowed": shared[0], "reason": shared[1]})
                    else:
                        library_decisions.append({**row, "allowed": both[0], "reason": both[1]})
    shapes = []
    for url in HOST_SHAPE_URLS:
        for opt_id, allow, text in OPT_INS[:2]:
            env = {} if text is None else {"FI_ALLOW_INSECURE_HTTP": text}
            allowed, reason = decide(url, env, allow, False, cpython_proxied)
            shapes.append({"id": f"{url}|{opt_id}", "url": url, "env": env, "allowInsecureHttp": allow,
                           "callerProxied": False, "allowed": allowed, "reason": reason})
    return {
        "description": DESCRIPTION,
        "reasons": REASONS,
        "envProxy": env_rows,
        "libraryEnvProxy": library_env_rows,
        "decisions": decisions,
        "libraryDecisions": library_decisions,
        "hostShapes": shapes,
        "channelPorts": [channel_port(url) for url in CHANNEL_URLS],
    }


def render(data: dict) -> str:
    return json.dumps(data, indent=1, ensure_ascii=True) + "\n"


def digest_line(text: str) -> str:
    return f"{hashlib.sha256(text.encode('utf-8')).hexdigest()}  {FIXTURE.name}\n"


def main(argv: list) -> int:
    text = render(build())
    digest = FIXTURE.with_name(FIXTURE.name + ".sha256")
    if "--write" in argv:
        FIXTURE.write_text(text, encoding="utf-8")
        digest.write_text(digest_line(text), encoding="utf-8")
        print(f"wrote {FIXTURE} ({digest_line(text).split()[0]})")
        return 0
    current = FIXTURE.exists() and FIXTURE.read_text(encoding="utf-8") == text
    current = current and digest.exists() and digest.read_text() == digest_line(text)
    print("up to date" if current else "out of date: run with --write")
    return 0 if current else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
