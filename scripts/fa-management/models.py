"""Project typed configuration sections from the gateway admin schema."""
import json


def kind(schema, defs, lang):
    if '$ref' in schema:
        schema = defs[schema['$ref'].rsplit('/', 1)[1]]
    if 'enum' in schema and all(isinstance(v, str) for v in schema['enum']):
        values = ', '.join(repr(v) for v in schema['enum'])
        return f'Literal[{values}]' if lang == 'py' else ' | '.join(json.dumps(v) for v in schema['enum'])
    typ = schema.get('type')
    if isinstance(typ, list):
        choices = [kind({**schema, 'type': value}, defs, lang) for value in typ if value != 'null']
        return ' | '.join(choices) if choices else ('Any' if lang == 'py' else 'unknown')
    if typ == 'array':
        item = kind(schema.get('items', {}), defs, lang)
        return f'list[{item}]' if lang == 'py' else f'Array<{item}>'
    types = {'string': ('str', 'string'), 'integer': ('int', 'number'), 'number': ('float', 'number'),
             'boolean': ('bool', 'boolean'), 'object': ('dict[str, Any]', 'Record<string, unknown>')}
    return types.get(typ, ('Any', 'unknown'))[lang == 'ts']


def models(admin, request_schema, excluded):
    py = ['# Generated by scripts/fa-management/generate.py. Do not edit.',
          'from typing import Any, Literal', 'from typing_extensions import TypedDict', '']
    ts = ['// Generated by scripts/fa-management/generate.py. Do not edit.', '']
    defs = admin['$defs']
    props = defs['OrgConfig']['properties']
    sections = {k:v for k,v in props.items() if k in request_schema['properties'] and k not in excluded['OrgConfig']}
    names = {}
    for section, schema in sections.items():
        if '$ref' not in schema:
            continue
        name = schema['$ref'].rsplit('/', 1)[1]
        names[section] = name
        py += [f'class {name}(TypedDict, total=False):', f'    """{section} fields from the gateway contract; null deletes a field in merge patches."""']
        ts += [f'/** {section} fields from the gateway contract; null deletes a field in merge patches. */', f'export interface {name} {{']
        fields = {k:v for k,v in defs[name].get('properties', {}).items() if k not in excluded.get(name, [])}
        for field, field_schema in fields.items():
            py += [f'    {field}: {kind(field_schema, defs, "py")} | None']
            ts += [f'  {json.dumps(field)}?: {kind(field_schema, defs, "ts")} | null;']
        if not fields:
            py += ['    pass']
        py += ['']
        ts += ['}', '']
    py += ['class ConfigSections(TypedDict, total=False):', '    """Typed sections. Raw mappings also preserve newer server fields and warnings."""']
    ts += ['/** Typed sections; a raw mapping may carry newer fields accepted by the server. */', 'export interface ConfigSections {']
    for section, schema in sections.items():
        py += [f'    {section}: {names.get(section, kind(schema, defs, "py"))} | None']
        ts += [f'  {section}?: {names.get(section, kind(schema, defs, "ts"))} | null;']
    py += ['', 'class ConfigUpdateResult(TypedDict, total=False):', '    """Wire result; warnings do not imply the mutation was rolled back."""',
           '    version: int', '    gateway_synced: bool', '    warnings: list[dict[str, Any]]', '    gateway_warning: str', '']
    ts += ['}', '', '/** Wire result; a warning does not imply that the mutation was rolled back. */',
           'export interface ConfigUpdateResult {', '  version?: number;', '  gateway_synced?: boolean;',
           '  warnings?: Array<Record<string, unknown>>;', '  gateway_warning?: string;', '  hasWarnings?: boolean;', '}', '']
    return '\n'.join(py), '\n'.join(ts)
