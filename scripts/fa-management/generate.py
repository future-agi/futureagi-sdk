"""Generate the scoped management spec, policy tables and language-twin namespaces."""
from __future__ import annotations

import argparse
import copy
import hashlib
import json
import re
import runpy
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "openapi/fa-mgmt"
PAGINATION = runpy.run_path(str(ROOT / "scripts/pagination_contracts.py"))


def camel(name):
    first, *rest = name.split("_")
    return first + "".join(part.title() for part in rest)


def title(name):
    return "".join(part.title() for part in name.replace(".", "_").split("_"))


def load_rows(source=SOURCE):
    swagger = json.loads((source / "swagger.json").read_text())
    surface = json.loads((source / "surface.json").read_text())
    recorded = json.loads((source / "overrides.json").read_text())
    index = {}
    for path, methods in swagger["paths"].items():
        for method, op in methods.items():
            if method not in ("get", "post", "patch", "put", "delete"):
                continue
            ident = op["operationId"]
            if ident in index:
                raise ValueError("duplicate operation id: " + ident)
            index[ident] = (path, method.upper(), op, methods.get("parameters", []))
    overrides = {}
    for override in recorded["overrides"]:
        fixture = (source / override["recording"]).resolve()
        if not fixture.is_relative_to(source.resolve()):
            raise ValueError("recordings must be under the contract directory")
        raw = fixture.read_bytes()
        if "sha256:" + hashlib.sha256(raw).hexdigest() != override["sha256"]:
            raise ValueError("recording digest mismatch")
        if override["operation_id"] not in index or override["operation_id"] in overrides:
            raise ValueError("unknown or duplicate override")
        capture = json.loads(raw)
        if capture.get("kind") != "control-plane-recording":
            raise ValueError("override must cite a control-plane recording")
        overrides[override["operation_id"]] = override["operation"]
    rows = []
    for admitted in surface["operations"]:
        path, method, operation, shared_params = index[admitted["operation_id"]]
        operation = {**operation, **overrides.get(admitted["operation_id"], {})}
        params = shared_params + operation.get("parameters", [])
        row = {**admitted, "method": method, "path": path,
               "path_params": re.findall(r"\{([^}]+)\}", path),
               "query": sorted({p["name"] for p in params if p["in"] == "query"} | set(admitted.get("extra_query", []))),
               "idempotent": False, "retry_class": "http-idempotent" if method in ("GET", "PUT", "DELETE") else "unsafe",
               "operation": operation}
        if not set(row.get("fixed_path", {})).issubset(row["path_params"]):
            raise ValueError("fixed path does not match Swagger")
        row["summary"] = PAGINATION["describe"](row["summary"], method, path)
        rows.append(row)
    names = [row["name"] for row in rows]
    if len(set(names)) != len(names):
        raise ValueError("duplicate public method")
    return rows, surface, swagger, recorded


def generate(root=ROOT):
    rows, surface, swagger, recorded = load_rows()
    pins = json.loads((SOURCE / 'source.json').read_text())
    public_admin = 'sha256:' + hashlib.sha256((SOURCE / 'admin.schema.json').read_bytes()).hexdigest()
    if pins.get('public_admin_sha256') != public_admin:
        raise ValueError('public admin schema digest mismatch; refresh the governed snapshot')
    admission_path = SOURCE / 'admission.json'
    admission = json.loads(admission_path.read_text())['state'] if admission_path.exists() else 'PROVISIONAL'
    if admission not in ('PROVISIONAL', 'HIDDEN'):
        raise ValueError('unknown management admission state')
    out = {}
    py = root / "python/fi/generated/platform/fa_management"
    ts = root / "typescript/futureagi/src/generated/fa-management"
    header = "Generated by scripts/fa-management/generate.py. Do not edit."
    pyp = [f'# {header}', 'from fi._core.policy import OperationSpec', '', 'OPERATIONS = {']
    tsp = [f'// {header}', 'import type { OperationTable } from "../../_core/policy";', '', 'export const MANAGEMENT_OPERATIONS: OperationTable = {']
    spec = {"swagger": "2.0", "info": swagger["info"], "basePath": swagger["basePath"], "paths": {}, "definitions": swagger["definitions"],
            "x-sdk-admin-schema": "../admin.schema.json", "x-sdk-envelope": {"status": "boolean", "result": "payload"},
            "x-sdk-qualification": admission, "x-sdk-pending-recordings": recorded["pending_recordings"]}
    mappings = []
    for row in rows:
        common = {"name": row["name"], "family": "gateway", "method": row["method"], "path": row["path"],
                  "body": "json" if row["method"] in ("POST", "PATCH", "PUT") else "none"}
        p = {**common, "path_params": tuple(row["path_params"]), "query": tuple(row["query"]), "operation_id": row["operation_id"]}
        t = {**common, "pathParams": row["path_params"], "query": row["query"], "operationId": row["operation_id"]}
        pyp.append(f'    {row["name"]!r}: OperationSpec(**{p!r}),')
        tsp.append(f'  {json.dumps(row["name"])}: {json.dumps(t)},')
        operation = copy.deepcopy(row["operation"])
        operation["x-sdk-management"] = {k: v for k, v in row.items() if k != "operation"}
        path_item = spec["paths"].setdefault(row["path"], {})
        path_item[row["method"].lower()] = operation
        if "parameters" in swagger["paths"][row["path"]]:
            path_item["parameters"] = copy.deepcopy(swagger["paths"][row["path"]]["parameters"])
        mappings.append({"operation_id": row["operation_id"], "python": row["name"], "python_async": row["name"],
                         "typescript": ".".join(camel(p) for p in row["name"].split(".")),
                         "arguments": [p for p in row["path_params"] if p not in row.get("fixed_path", {})] + ([row["body_arg"]] if row.get("body_arg") else []),
                         "query": row["query"], "fixed_path": row.get("fixed_path", {}), "status": admission})
    for excluded in surface["not_offered"]:
        mappings.append({"operation_id": excluded["operation_id"], "python": "NOT-OFFERED", "python_async": "NOT-OFFERED", "typescript": "NOT-OFFERED", "reason": excluded["reason"]})
    pyp.append('}')
    tsp.append('};')
    out[py / "policy.py"] = "\n".join(pyp) + "\n"
    out[ts / "policy.ts"] = "\n".join(tsp) + "\n"
    out[py / "__init__.py"] = '"""Generated management namespaces. Use FutureAGIClient.gateway."""\n'
    groups = sorted({r["name"].rsplit(".", 1)[0] for r in rows} | {"gateway"}, key=lambda s: (-len(s), s))
    pyp = [f'# {header}', 'from typing import Any, Mapping', 'from fi._core.fa_management import ManagementResource, AsyncManagementResource',
           'from fi.generated.platform.fa_management.models import ConfigSections, ConfigUpdateResult', '']
    tsp = [f'// {header}', 'import { ManagementResource, ManagementPage } from "../../_core/fa-management";',
           'import type { ConfigSections, ConfigUpdateResult } from "./models";', '']
    for group in groups:
        own = [r for r in rows if r["name"].rsplit(".", 1)[0] == group]
        children = [g for g in groups if g.rpartition(".")[0] == group]
        for asynchronous in (True, False):
            prefix = "Async" if asynchronous else ""
            pyp += [f'class {prefix}{title(group)}({prefix}ManagementResource):', f'    """{group}: generated management operations."""']
            for child in children:
                pyp += ['    @property', f'    def {child.rsplit(".", 1)[1]}(self) -> "{prefix}{title(child)}":',
                        f'        """The {child} namespace."""', f'        return {prefix}{title(child)}(self._core)', '']
            for row in own:
                args = [p + ': str' for p in row["path_params"] if p not in row.get("fixed_path", {})]
                body = row.get("body_arg")
                if body:
                    typ = 'ConfigSections | Mapping[str, Any]' if row["name"] in ("gateway.config.update", "gateway.config.create_version") else 'Mapping[str, Any]'
                    args += [f'{body}: {typ}']
                args += ['*', 'strict: bool = False', '**query: Any']
                paths = '{' + ', '.join(repr(p)+': '+(repr(row['fixed_path'][p]) if p in row.get('fixed_path', {}) else p) for p in row['path_params']) + '}'
                result = 'ConfigUpdateResult' if row["name"] == 'gateway.config.update' else 'Any'
                pyp += [f'    {"async " if asynchronous else ""}def {row["name"].split(".")[-1]}(self, {", ".join(args)}) -> {result}:',
                        f'        """{row["summary"]}"""',
                        f'        return {"await " if asynchronous else ""}self._call({row["name"]!r}, path={paths}, query=query, body={body or "None"}, paged={row.get("page", False)}, strict=strict)', '']
        tsp += [f'export class {title(group)} extends ManagementResource {{']
        for child in children:
            tsp += [f'  /** The {child} namespace. */', f'  get {camel(child.split(".")[-1])}(): {title(child)} {{ return new {title(child)}(this.core); }}']
        for row in own:
            args = [camel(p) + ': string' for p in row['path_params'] if p not in row.get('fixed_path', {})]
            body = row.get('body_arg')
            if body:
                typ = 'ConfigSections | Record<string, unknown>' if row['name'] in ('gateway.config.update', 'gateway.config.create_version') else 'Record<string, unknown>'
                args += [f'{body}: {typ}']
            args += ['query: Record<string, unknown> = {}', 'options: { strict?: boolean } = {}']
            paths = '{' + ', '.join(json.dumps(p)+': '+(json.dumps(row['fixed_path'][p]) if p in row.get('fixed_path', {}) else camel(p)) for p in row['path_params']) + '}'
            result = 'ManagementPage' if row.get('page') else 'ConfigUpdateResult' if row['name'] == 'gateway.config.update' else 'any'
            tsp += [f'  /** {row["summary"]} */', f'  {camel(row["name"].split(".")[-1])}({", ".join(args)}) {{',
                    f'    return this.call<{result}>({json.dumps(row["name"])}, {paths}, query, {body or "undefined"}, {str(row.get("page", False)).lower()}, options.strict ?? false);', '  }']
        tsp += ['}', '']
    out[py / 'gateway.py'] = '\n'.join(pyp).rstrip() + '\n'
    out[ts / 'gateway.ts'] = '\n'.join(tsp).rstrip() + '\n'
    out[root / 'openapi/fa-mgmt/generated/spec.json'] = json.dumps(spec, indent=2, sort_keys=True) + '\n'
    out[root / 'openapi/fa-mgmt/generated/operations.json'] = json.dumps([{k:v for k,v in r.items() if k != 'operation'} for r in rows], indent=2, sort_keys=True) + '\n'
    out[root / 'openapi/fa-mgmt/wrapper-map.json'] = json.dumps({"operations": mappings, "pending_recordings": recorded['pending_recordings']}, indent=2, sort_keys=True) + '\n'
    model_generator = runpy.run_path(str(Path(__file__).with_name('models.py')))
    update = next(row['operation'] for row in rows if row['name'] == 'gateway.config.update')
    request_schema = next(p['schema'] for p in update['parameters'] if p['in'] == 'body')
    if '$ref' in request_schema:
        request_schema = swagger['definitions'][request_schema['$ref'].rsplit('/', 1)[1]]
    model_py, model_ts = model_generator['models'](json.loads((SOURCE / 'admin.schema.json').read_text()), request_schema, surface['untyped_config_fields'])
    out[py / 'models.py'], out[ts / 'models.ts'] = model_py, model_ts
    if admission == 'HIDDEN':
        out = {path: text for path, text in out.items() if not path.is_relative_to(py) and not path.is_relative_to(ts)}
    return out


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--out', type=Path, default=ROOT)
    args = parser.parse_args()
    legacy = args.out / 'python/fi/generated/fa_management'
    for path in sorted(legacy.glob('*.py')):
        if args.check:
            raise SystemExit(f'obsolete generated output: {path}')
        if 'Generated' not in path.read_text():
            raise SystemExit(f'refusing to remove a non-generated file: {path}')
        path.unlink()
    if legacy.exists() and not list(legacy.iterdir()):
        legacy.rmdir()
    produced = generate(args.out)
    for folder in ('python/fi/generated/platform/fa_management', 'typescript/futureagi/src/generated/fa-management'):
        for path in (args.out / folder).glob('*'):
            if path.is_file() and path not in produced:
                if args.check:
                    raise SystemExit(f'stale generated output: {path}')
                if 'Generated' not in path.read_text():
                    raise SystemExit(f'refusing to remove a non-generated file: {path}')
                path.unlink()
    for path, text in produced.items():
        if path.suffix in ('.py', '.ts') and len(text.splitlines()) > 400:
            raise SystemExit(f'module exceeds 400 lines: {path}')
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f'generated output differs: {path}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
