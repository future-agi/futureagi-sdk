"""Generate the admitted FA catalog slice on the shared client core. No dependencies."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from pagination_contracts import describe

ROOT = Path(__file__).resolve().parents[1]
PY = ROOT / "python/fi/generated/platform/catalog"
TS = ROOT / "typescript/futureagi/src/generated/catalog"


def camel(name):
    first, *rest = name.split("_")
    return first + "".join(word.title() for word in rest)


def title(name):
    return "".join(word.title() for word in name.replace(".", "_").split("_"))


def outputs(root: Path = ROOT):
    py_root = root / PY.relative_to(ROOT)
    ts_root = root / TS.relative_to(ROOT)
    rows = json.loads((ROOT / "openapi/catalog/operations.json").read_text())["operations"]
    rows = [{**r, "description": describe(r.get("description", ""), r["method"], r["path"])} for r in rows]
    result = {py_root / "__init__.py": '"""Generated FA namespaces; use FutureAGIClient."""\n'}
    families = sorted({r["id"].split(".")[0] for r in rows})
    for family in families:
        ops = [r for r in rows if r["id"].split(".")[0] == family]
        groups = sorted({r["id"].rsplit(".", 1)[0] for r in ops}, key=lambda s: (-len(s), s))
        py = ['# Generated by scripts/generate-catalog-namespaces.py. Do not edit.',
              'from typing import Any, Mapping',
              'from fi._core.catalog import Resource, AsyncResource',
              'from fi._core.policy import OperationSpec', '']
        ts = ['// Generated by scripts/generate-catalog-namespaces.py. Do not edit.',
              'import { Resource, type CatalogOperation } from "../../_core/catalog";',
              'import { PagePromise } from "../../_core/pagination";', '']
        for r in ops:
            name = r["id"].upper().replace(".", "_")
            spec = dict(name=r["public"], family=family, method=r["method"], path=r["path"],
                        path_params=tuple(r["path_params"]), query=tuple(r["query"]),
                        body="json" if r["method"] in ("POST", "PUT", "PATCH") else "none",
                        operation_id=r["operation_id"])
            py += [f'{name} = (OperationSpec(**{spec!r}), {r["unwrap"]!r}, {r["pagination"]!r})']
            wire = {key: value for key, value in r.items() if key != "description"}
            ts += [f'const {name}: CatalogOperation = {json.dumps(wire)};']
        for group in groups:
            own = [r for r in ops if r["id"].rsplit(".", 1)[0] == group]
            children = [g for g in groups if g.rpartition(".")[0] == group]
            for async_ in (False, True):
                prefix = "Async" if async_ else ""
                py += ['', f'class {prefix}{title(group)}({prefix}Resource):']
                for child in children:
                    py += ['    @property', f'    def {child.rsplit(".", 1)[1]}(self) -> "{prefix}{title(child)}":',
                           f'        return {prefix}{title(child)}(self._client)', '']
                for r in own:
                    method = r["id"].rsplit(".", 1)[1]
                    args = [f'{p}: str' for p in r["path_params"]]
                    path = "{" + ", ".join(f'{p!r}: {p}' for p in r["path_params"]) + "}"
                    if r["method"] in ("POST", "PUT", "PATCH"):
                        args += ['body: Mapping[str, Any] | None = None']
                    args += ['**query: Any']
                    name = r["id"].upper().replace(".", "_")
                    body = "body" if r["method"] in ("POST", "PUT", "PATCH") else "None"
                    py += [f'    {"async " if async_ else ""}def {method}(self, {", ".join(args)}) -> Any:']
                    if r.get("description"):
                        py += [f'        {r["description"]!r}']
                    py += [f'        return {"await " if async_ else ""}self._call({name}, path={path}, query=query, body={body})', '']
            ts += ['', f'export class {title(group)} extends Resource {{']
            for child in children:
                ts += [f'  get {camel(child.rsplit(".", 1)[1])}(): {title(child)} {{ return new {title(child)}(this.client, this.headers); }}']
            for r in own:
                args = [f'{camel(p)}: string' for p in r["path_params"]]
                path = "{" + ", ".join(f'{p}: {camel(p)}' for p in r["path_params"]) + "}"
                body = "undefined"
                if r["method"] in ("POST", "PUT", "PATCH"):
                    args += ['body?: Record<string, unknown>']
                    body = "body"
                args += ['query: Record<string, unknown> = {}']
                name = r["id"].upper().replace(".", "_")
                call = f'this.call({name}, {path}, query, {body})'
                if r["pagination"]:
                    call = f'new PagePromise<Record<string, unknown>>({call})'
                if r.get("description"):
                    ts += [f'  /** {r["description"]} */']
                ts += [f'  {camel(r["id"].rsplit(".", 1)[1])}({", ".join(args)}) {{',
                       f'    return {call};', '  }']
            ts += ['}']
        result[py_root / f"{family}.py"] = "\n".join(py).rstrip("\n") + "\n"
        result[ts_root / f"{family}.ts"] = "\n".join(ts) + "\n"
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--out", type=Path, default=ROOT, help="output root for isolated regeneration")
    args = parser.parse_args()
    legacy = args.out / "python/fi/generated/catalog"
    for path in legacy.glob("*.py"):
        if args.check:
            raise SystemExit(f"obsolete generated output: {path}")
        if "Generated" not in path.read_text():
            raise SystemExit(f"refusing to remove a non-generated file: {path}")
        path.unlink()
    produced = outputs(args.out)
    for folder, pattern in ((args.out / PY.relative_to(ROOT), "*.py"),
                            (args.out / TS.relative_to(ROOT), "*.ts")):
        for path in sorted(folder.glob(pattern)):
            if path in produced:
                continue
            if args.check:
                raise SystemExit(f"stale generated output: {path}")
            if "Generated" not in path.read_text():
                raise SystemExit(f"refusing to remove a non-generated file: {path}")
            path.unlink()
    for path, text in produced.items():
        if len(text.splitlines()) > 400:
            raise SystemExit(f"module exceeds 400 lines: {path}")
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f"generated output differs: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)


if __name__ == "__main__":
    main()
