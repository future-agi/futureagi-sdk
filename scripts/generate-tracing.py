#!/usr/bin/env python3
"""Generate Observe query twins from the pinned contract and public wrapper map."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from licensed_operation_docs import licensing_note
from pagination_contracts import describe

ROOT = Path(__file__).resolve().parents[1]


def camel(name):
    first, *rest = name.split('_')
    return first + ''.join(word.title() for word in rest)


def method_doc(row):
    text = describe(row['py'].replace('_', ' ').capitalize() + ' using the authenticated client transport.',
                    row['method'], row['path'])
    note = licensing_note(row['path'])
    return text + (' ' + note if note else '')


def outputs():
    source = json.loads((ROOT / 'openapi/tracing/source.json').read_text())
    rows = json.loads((ROOT / 'openapi/tracing/wrapper-map.json').read_text())['operations']
    py = ['# Generated by scripts/generate-tracing.py. Do not edit.',
          'from typing import Any',
          'from fi._core.catalog import AsyncResource, Resource',
          'from fi._core.policy import OperationSpec', '']
    ts = ['// Generated by scripts/generate-tracing.py. Do not edit.',
          'import { Resource, type CatalogOperation } from "../_core/catalog";', '']
    for row in rows:
        op = source['paths'][row['path']][row['method'].lower()]
        if op['operationId'] != row['operation_id']:
            raise ValueError(f"operation identity changed: {row['py']}")
        query = list(dict.fromkeys([p['name'] for p in op['parameters'] if p['in'] == 'query'] + row['compat_query']))
        spec = dict(name=row['public']['py'], family='tracing', method=row['method'],
                    path=row['path'], path_params=tuple(row['args']), query=tuple(query),
                    body='json' if row['method'] in ('POST', 'PATCH', 'PUT') else 'none',
                    operation_id=row['operation_id'])
        py += [f"{row['py'].upper()} = (OperationSpec(**{spec!r}), None, None)"]
        metadata = dict(id='tracing.' + row['py'], public='tracing.' + row['py'],
                        method=row['method'], path=row['path'], path_params=list(row['args']),
                        query=query, operation_id=row['operation_id'], unwrap=None, pagination=None)
        ts += [f"const {row['py'].upper()}: CatalogOperation = {json.dumps(metadata)};"]
    for asynchronous in (True, False):
        prefix = 'Async' if asynchronous else ''
        py += ['', f'class {prefix}TracingQueries({prefix}Resource):',
               '    """Observe operations; preserves response envelopes and page metadata."""']
        for row in rows:
            args = [f'{name}: str' for name in row['args'].values()]
            body = row['method'] in ('POST', 'PATCH', 'PUT')
            if body:
                args += ['body: Any']
            args += ['**query: Any']
            paths = '{' + ', '.join(f'{key!r}: {name}' for key, name in row['args'].items()) + '}'
            py += [f"    {'async ' if asynchronous else ''}def {row['py']}(self, {', '.join(args)}) -> Any:",
                   f'        """{method_doc(row)}"""',
                   f"        return {'await ' if asynchronous else ''}self._call({row['py'].upper()}, path={paths}, query=query, body={'body' if body else 'None'})", '']
    ts += ['', '/** Observe queries preserve response envelopes and pagination metadata. */',
           'export class TracingQueries extends Resource {']
    for row in rows:
        args = [f'{camel(name)}: string' for name in row['args'].values()]
        body = row['method'] in ('POST', 'PATCH', 'PUT')
        if body:
            args += ['body: Record<string, unknown>']
        args += ['query: Record<string, unknown> = {}']
        paths = '{' + ', '.join(f'{key}: {camel(name)}' for key, name in row['args'].items()) + '}'
        ts += [f"  /** {method_doc(row)} */",
               f"  {row['ts']}({', '.join(args)}) {{",
               f"    return this.call({row['py'].upper()}, {paths}, query, {'body' if body else 'undefined'});", '  }']
    ts += ['}']
    return {'python/fi/generated/platform/tracing.py': '\n'.join(py).rstrip() + '\n',
            'typescript/futureagi/src/generated/tracing.ts': '\n'.join(ts).rstrip() + '\n'}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', type=Path, default=ROOT)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, text in outputs().items():
        if len(text.splitlines()) > 400:
            raise SystemExit(f'module exceeds 400 lines: {name}')
        path = args.out / name
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f'generated output differs: {name}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)


if __name__ == '__main__':
    main()
