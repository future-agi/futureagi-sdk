"""Render the pagination table's documentation into hand-maintained facades.

Generated namespaces get the same text from their own generators. This renderer
changes docstrings/JSDoc only; it never changes query serialization or signatures.
"""
from __future__ import annotations

import argparse
import ast
import re
from collections import defaultdict
from pathlib import Path

from pagination_contracts import ROOT, rows


def python_nodes(source):
    found = {}
    def walk(node, prefix=""):
        for child in ast.iter_child_nodes(node):
            if isinstance(child, ast.ClassDef):
                walk(child, prefix + child.name + ".")
            elif isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef)):
                found[prefix + child.name] = child
    walk(ast.parse(source))
    return found


def render_python(source, notes):
    lines = source.splitlines(keepends=True)
    nodes = python_nodes(source)
    edits = []
    for symbol, note in notes.items():
        node = nodes[symbol]
        current = ast.get_docstring(node)
        first = node.body[0]
        indent = " " * first.col_offset
        if current and note in " ".join(current.split()):
            text = current
        elif current and note.startswith(current):
            text = note
        else:
            text = (current + "\n\n" if current else "") + note
        text = text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
        doc_lines = [line.rstrip() for line in text.splitlines()]
        literal = indent + '"""' + doc_lines[0] + "".join("\n" + (indent + line if line else "") for line in doc_lines[1:]) + '"""\n'
        end = first.end_lineno if current is not None else first.lineno - 1
        edits.append((first.lineno - 1, end, literal))
    for start, end, text in sorted(edits, reverse=True):
        lines[start:end] = [text]
    return "".join(lines)


def render_typescript(source, notes):
    edits = []
    classes = list(re.finditer(r"^export class (\w+)", source, re.M))
    for i, cls in enumerate(classes):
        end = classes[i + 1].start() if i + 1 < len(classes) else len(source)
        for method in re.finditer(r"^  (?:(?:public|private|protected|async|static|override) )*(\w+)\s*\(", source[cls.start():end], re.M):
            note = notes.get(cls[1] + "." + method[1])
            if not note:
                continue
            start = cls.start() + method.start()
            prefix = source[:start]
            comment = re.search(r"/\*\*(?:(?!\*/)[\s\S])*\*/\s*$", prefix)
            if comment:
                old = comment[0]
                if note in re.sub(r"\s+", " ", re.sub(r"\n\s*\* ?", " ", old)):
                    continue
                close = prefix.rfind("*/")
                body = re.sub(r"\s+", " ", re.sub(r"\n\s*\* ?", " ", old[:old.rfind("*/")][3:])).strip()
                addition = note[len(body):].lstrip() if note.startswith(body) else note
                edits.append((close, close, addition + " "))
            else:
                edits.append((start, start, "  /** " + note + " */\n"))
    for start, end, text in sorted(edits, reverse=True):
        source = source[:start] + text + source[end:]
    return source


def outputs():
    grouped = defaultdict(dict)
    for row in rows():
        for language, refs in row["methods"].items():
            for ref in refs:
                path = ROOT / ref["file"]
                if "generated" in path.parts:
                    continue
                extra = row.get("wrapper_notes", {}).get(ref["symbol"], "")
                grouped[path][ref["symbol"]] = row["documentation"] + (" " + extra if extra else "")
    result = {}
    for path, notes in grouped.items():
        source = path.read_text()
        if "Generated by" in source.splitlines()[0]:
            continue
        result[path] = (render_python if path.suffix == ".py" else render_typescript)(source, notes)
    return result


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in outputs().items():
        if args.check:
            if content != path.read_text():
                raise SystemExit(f"Pagination documentation differs: {path}")
        else:
            path.write_text(content)
