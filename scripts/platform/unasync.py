#!/usr/bin/env python3
"""Generate the synchronous twin of every async-first platform module.

    python3 scripts/platform/unasync.py             # write the sync twins in the tree
    python3 scripts/platform/unasync.py --out DIR   # write them under DIR (python/fi/... layout)
    python3 scripts/platform/unasync.py --list      # print source -> twin pairs

Behaviour is written once, async-first. The pairs are found, not listed:

- ``python/fi/<namespace>/**/_async_client.py`` -> the sibling ``_client.py``, for every platform
  namespace in ``NAMESPACES``;
- ``python/fi/_core/**/_async/<module>.py`` -> ``python/fi/_core/**/_sync/<module>.py``.

The transform is pinned by being this file: standard library only, token based (``tokenize``), so it
never touches text inside a string or comment except through the explicit ``TEXT`` rules, and its
output is deterministic. ``scripts/generate-platform-sdk.sh`` formats the twins with the pinned black,
and ``scripts/platform/check.sh`` regenerates them and diffs. The rules:

- ``async def`` / ``async for`` / ``async with`` lose ``async``; ``await`` is removed;
- ``Awaitable[X]`` becomes ``X`` (and ``Awaitable`` leaves an import list);
- a name ``Async<Upper>...`` loses its ``Async`` prefix (``AsyncFutureAGIClient`` ->
  ``FutureAGIClient``, ``AsyncSandbox`` -> ``Sandbox``, ``AsyncIterator`` -> ``Iterator``), and the
  names in ``NAMES`` are renamed (``aclose`` -> ``close``, ``_async`` -> ``_sync`` ...);
- strings and comments get the ``TEXT`` and ``TEXT_PATTERNS`` rules, so docstrings, comments and
  string annotations describe the sync API.
"""

from __future__ import annotations

import argparse
import io
import re
import sys
import tokenize
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
PKG = REPO / "python" / "fi"
#: The platform namespaces whose ``_async_client.py`` modules get a sync twin.
NAMESPACES = (
    "deployments",
    "sandboxes",
    "agents",
    "environments",
    "workspace",
    # The data-plane gateway clients are independently ported, not generated twins.
    # Only its platform management subtree belongs to this generator.
    "gateway/management",
    "connectors",
)
ASYNC_NAME = re.compile(r"^Async(?=[A-Z])")

NAMES = {
    "aiter_bytes": "iter_bytes",
    "aiter_raw": "iter_raw",
    "aiter_lines": "iter_lines",
    "aiter_text": "iter_text",
    "aread": "read",
    "aclose": "close",
    "__aenter__": "__enter__",
    "__aexit__": "__exit__",
    "__aiter__": "__iter__",
    "__anext__": "__next__",
    "anext": "next",
    "asynccontextmanager": "contextmanager",
    "_async": "_sync",
    "_async_client": "_client",
    "alist_page": "list_page",
    "apoll_until": "poll_until",
    "resumable_events": "resumable_events_sync",
}

TEXT = (
    ("httpx.AsyncClient", "httpx.Client"),
    ("(async)", "(sync)"),
    ("_async_client.py", "_client.py"),
    ("/_async/", "/_sync/"),
)
#: Word-level rules for strings and comments: ``async with`` / ``async for`` / ``async def`` lose
#: ``async``, ``await`` goes, and a name ``Async<Upper>...`` loses its prefix.
TEXT_PATTERNS = (
    (re.compile(r"\basync (?=(?:with|for|def)\b)"), ""),
    (re.compile(r"\bawait "), ""),
    (re.compile(r"\bAsync(?=[A-Z])"), ""),
)


def header(source: str) -> str:
    return f"# GENERATED by scripts/platform/unasync.py from {source}. Do not edit.\n"


def _offsets(text: str) -> list[int]:
    starts, total = [0], 0
    for line in text.splitlines(keepends=True):
        total += len(line)
        starts.append(total)
    return starts


def _text(value: str) -> str:
    for old, new in TEXT:
        value = value.replace(old, new)
    for pattern, new in TEXT_PATTERNS:
        value = pattern.sub(new, value)
    return value


def _rename(name: str) -> str | None:
    if name in NAMES:
        return NAMES[name]
    if ASYNC_NAME.match(name):
        return ASYNC_NAME.sub("", name)
    return None


def transform(text: str, source: str) -> str:
    """The sync twin of one async module's text (``source`` is its repository-relative path)."""
    starts = _offsets(text)
    tokens = list(tokenize.generate_tokens(io.StringIO(text).readline))
    edits: list[tuple[int, int, str]] = []

    def at(pos: tuple[int, int]) -> int:
        return starts[pos[0] - 1] + pos[1]

    for i, tok in enumerate(tokens):
        start, end = at(tok.start), at(tok.end)
        if tok.type == tokenize.NAME and tok.string in ("async", "await"):
            nxt = tokens[i + 1]
            if tok.string == "async" and nxt.string not in ("def", "for", "with"):
                raise SystemExit(
                    f"{source}:{tok.start[0]}: 'async' before {nxt.string!r} has no sync form"
                )
            edits.append((start, at(nxt.start), ""))
        elif (
            tok.type == tokenize.NAME
            and tok.string == "Awaitable"
            and tokens[i + 1].string == "["
        ):
            depth, j = 0, i + 1
            while True:
                if tokens[j].string == "[":
                    depth += 1
                elif tokens[j].string == "]":
                    depth -= 1
                    if depth == 0:
                        break
                j += 1
            edits.append((start, at(tokens[i + 1].end), ""))
            edits.append((at(tokens[j].start), at(tokens[j].end), ""))
        elif (
            tok.type == tokenize.NAME
            and tok.string == "Awaitable"
            and tokens[i + 1].string == ","
        ):
            edits.append(
                (start, at(tokens[i + 2].start), "")
            )  # an import list entry with no sync use
        elif (
            tok.type == tokenize.NAME
            and tok.string == "Awaitable"
            and tokens[i - 1].string == ","
        ):
            edits.append(
                (at(tokens[i - 1].start), end, "")
            )  # the last entry of an import list
        elif tok.type == tokenize.NAME and _rename(tok.string) is not None:
            edits.append((start, end, _rename(tok.string) or ""))
        elif tok.type in (tokenize.STRING, tokenize.COMMENT):
            replaced = _text(tok.string)
            if replaced != tok.string:
                edits.append((start, end, replaced))
    out = text
    for start, end, new in sorted(edits, reverse=True):
        out = out[:start] + new + out[end:]
    return header(source) + out


def pairs(pkg: Path = PKG) -> list[tuple[Path, Path]]:
    """``(async source, sync twin)`` for every platform module, sorted."""
    found: list[tuple[Path, Path]] = []
    for namespace in NAMESPACES:
        for source in (
            sorted((pkg / namespace).rglob("_async_client.py"))
            if (pkg / namespace).is_dir()
            else []
        ):
            found.append((source, source.with_name("_client.py")))
    core = pkg / "_core"
    for source in sorted(core.rglob("*.py")) if core.is_dir() else []:
        if source.parent.name == "_async" and "__pycache__" not in source.parts:
            found.append((source, source.parent.with_name("_sync") / source.name))
    return found


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(
        description="Generate the sync twins of the async-first platform modules."
    )
    parser.add_argument(
        "--out",
        type=Path,
        help="write the twins under this directory instead of the tree",
    )
    parser.add_argument("--list", action="store_true", help="print the pairs and exit")
    args = parser.parse_args(argv)
    for source, twin in pairs():
        rel_source = source.relative_to(REPO).as_posix()
        rel_twin = twin.relative_to(REPO)
        if args.list:
            print(f"{rel_source} -> {rel_twin.as_posix()}")
            continue
        target = (args.out / rel_twin) if args.out else twin
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(
            transform(source.read_text(encoding="utf-8"), rel_source), encoding="utf-8"
        )
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
