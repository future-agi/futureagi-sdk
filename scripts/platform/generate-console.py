#!/usr/bin/env python3
"""Generate thin Console facades from the scoped contract and wrapper map.

The async Python implementation is emitted first; unasync.py produces its sync twin.
Responses retain unknown server fields. Request bodies use the contract's wire keys.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
GROUPS = {
    "agents": ("Agents", "platform.agents.", "agents"),
    "schedules": ("Schedules", "platform.schedules.", "agents/schedules"),
    "environments": ("Environments", "platform.environments.", "environments"),
}


def write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def main() -> None:
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', type=Path, default=ROOT)
    destination = parser.parse_args().out
    mapping = json.loads((ROOT / "openapi/platform/wrapper-map.json").read_text())
    spec = json.loads((ROOT / "openapi/platform/generated/futureagi-platform.openapi.json").read_text())
    operations = {}
    for item in spec["paths"].values():
        for verb in ("get", "post", "patch", "put", "delete"):
            if verb in item:
                op = item[verb]
                sdk = op["x-omega-sdk"]
                operations[sdk["family"] + "." + sdk["method"]] = (item, op)
    for group, (cls, prefix, directory) in GROUPS.items():
        py = [
            '# GENERATED by scripts/platform/generate-console.py. Do not edit.',
            '"""Async Console methods using the shared generated operation table."""',
            'from __future__ import annotations',
            'from typing import Any, cast',
            'from functools import cached_property',
            'from fi._core.raw import AsyncNamespace',
            'from fi.generated.platform import types as T',
            '', f'class Async{cls}(AsyncNamespace):',
            f'    """{cls} in the selected workspace; no requests occur on construction."""',
            '    def __init__(self, client: Any) -> None:',
            '        self._client = client',
        ]
        depth = '../../' if group == 'schedules' else '../'
        ts = [
            '// GENERATED by scripts/platform/generate-console.py. Do not edit.',
            f'import type * as T from "{depth}generated/platform/types.gen";',
            f'import type {{ PlatformCore, CallOptions }} from "{depth}_core/platform-base";',
            f'import type {{ APIPromise }} from "{depth}_core/raw";',
            f'import {{ ConfigurationError }} from "{depth}_core/errors";',
            f'/** {cls} in the selected workspace; construction sends no requests. */',
            f'export class {cls} {{',
            '  readonly #client: { readonly _platform: PlatformCore };',
            '  /** Bind the shared client without resolving credentials or opening a connection. */',
            '  constructor(client: { readonly _platform: PlatformCore }) { this.#client = client; }',
        ]
        if group == 'agents':
            py += ['', '    @property', '    def schedules(self) -> Any:',
                   '        """Workspace schedules sharing this client and its options."""',
                   '        from .schedules._async_client import AsyncSchedules',
                   '        return AsyncSchedules(self._client)',
                   '', '    @cached_property', '    def code(self) -> Any:',
                   '        """Default-off portable authored definitions; never starts a run."""',
                   '        from .code._async_client import AsyncAgentCode',
                   '        return AsyncAgentCode(self._client)']
            py += ['', '    @property', '    def runs(self) -> Any:',
                   '        """Conversations sharing this client and its platform executor."""',
                   '        from .runs import AsyncRuns',
                   '        return AsyncRuns(self._client._platform)',
                   '', '    @property', '    def ratings(self) -> Any:',
                   '        """Caller-scoped aggregate satisfaction reads."""',
                   '        from .runs import AsyncRatings',
                   '        return AsyncRatings(self._client._platform)']
            ts.insert(1, 'import { Schedules } from "./schedules/client";')
            ts.insert(2, 'import { Ratings, Runs } from "./runs";')
            ts += ['  /** Workspace schedules sharing this client and its options. */',
                   '  get schedules(): Schedules { return new Schedules(this.#client); }',
                   '  /** Conversations sharing this client and its platform executor. */',
                   '  get runs(): Runs { return new Runs(this.#client._platform); }',
                   '  /** Caller-scoped aggregate satisfaction reads. */',
                   '  get ratings(): Ratings { return new Ratings(this.#client._platform); }']
        for name, entry in mapping['operations'].items():
            if not name.startswith(prefix) or not entry.get('methods'):
                continue
            method = entry['methods'][0]
            item, op = operations[name]
            if op.get('x-omega-human-only'):
                raise ValueError(f'Human-only operation cannot have a facade: {name}')
            if op.get('x-omega-pagination', {}).get('style') not in (None, 'single-page'):
                raise ValueError(f'{name} needs a cursor-aware facade before generation')
            if any(p.get('in') == 'query' for p in item.get('parameters', []) + op.get('parameters', [])):
                raise ValueError(f'{name} needs explicit query support before generation')
            import re
            route = next(route for route, value in spec['paths'].items() if value is item)
            path_keys = re.findall(r'\{([^}]+)\}', route)
            pyname, tsname = method['py'].split('.')[-1], method['ts'].split('.')[-1]
            pyargs = method['py_args'][:method['py_args'].index('*')] if '*' in method['py_args'] else method['py_args']
            tsargs = [a for a in method['ts_args'] if not a.startswith('options.')]
            if len(pyargs) != len(path_keys) or len(tsargs) != len(path_keys):
                raise ValueError(f'Path argument mismatch for {name}')
            body = entry.get('body', {}).get('schema')
            optional = not op.get('requestBody', {}).get('required', False)
            keyed = op.get('x-omega-idempotent') is True
            response = entry['response']
            pos_py = [f'{arg}: {"int" if arg in ("version", "revision") else "str"}' for arg in pyargs]
            pos_ts = [f'{arg}: {"number" if arg in ("version", "revision") else "string"}' for arg in tsargs]
            kw_py = ([f'body: T.{body}' + (' | None = None' if optional else '')] if body else [])
            if keyed:
                kw_py += ['idempotency_key: str | None = None']
            kw_py += ['timeout: float | None = None', 'retries: int | None = None']
            sig = ', '.join(['self', *pos_py, '*', *kw_py])
            py += ['', f'    async def {pyname}({sig}) -> T.{response}:',
                   f'        """{op.get("summary", pyname).replace(chr(34), chr(39))}. Return the complete response envelope."""']
            py += ['        from fi.errors import ConfigurationError']
            for arg in pyargs:
                if arg in ('version', 'revision'):
                    py += [f'        if type({arg}) is not int or not 1 <= {arg} <= 9007199254740991:',
                           f'            raise ConfigurationError("{arg} must be a positive safe integer", code="invalid_revision")']
            path_py = '{' + ', '.join(f'"{key}": {arg}' for key, arg in zip(path_keys, pyargs)) + '}'
            params_py = [f'path={path_py}'] if path_keys else []
            if body:
                params_py += ['body=body']
            if keyed:
                # A schedule may put its durable identity in its body. Never mint a conflicting header.
                if group == 'schedules':
                    py += ['        body_key = (body or {}).get("idempotencyKey")',
                           '        if body_key is not None:',
                           '            if idempotency_key is not None and idempotency_key != body_key:',
                           '                raise ConfigurationError("Body and header idempotency keys must match", code="idempotency_key_mismatch")',
                           '            idempotency_key = body_key']
                params_py += ['idempotency_key=idempotency_key']
            params_py += ['timeout=timeout', 'retries=retries']
            py += [f'        return cast(T.{response}, await self._client._platform.call(',
                   f'            "{name}", {", ".join(params_py)}))']
            opts = 'CallOptions' if keyed else 'Omit<CallOptions, "idempotencyKey">'
            if body:
                opts += f' & {{ body{"?" if optional else ""}: T.{body} }}'
            pos_ts += [f'options: {opts}' + (' = {}' if not body or optional else '')]
            ts += [f'  /** {op.get("summary", tsname)}. Returns the complete response envelope. */',
                   f'  {tsname}({", ".join(pos_ts)}): APIPromise<T.{response}> {{']
            for arg in tsargs:
                if arg in ('version', 'revision'):
                    ts += [f'    if (!Number.isSafeInteger({arg}) || {arg} < 1)',
                           f'      throw new ConfigurationError("{arg} must be a positive safe integer", "invalid_revision");']
            if keyed and group == 'schedules':
                ts += ['    const bodyKey = options.body?.idempotencyKey;',
                       '    if (bodyKey !== undefined) {',
                       '      if (options.idempotencyKey !== undefined && options.idempotencyKey !== bodyKey)',
                       '        throw new ConfigurationError("Body and header idempotency keys must match", "idempotency_key_mismatch");',
                       '      options = { ...options, idempotencyKey: bodyKey };', '    }']
            path_ts = '{ ' + ', '.join(f'{key}: {arg}' for key, arg in zip(path_keys, tsargs)) + ' }'
            params_ts = [f'path: {path_ts}'] if path_keys else []
            if body:
                params_ts += ['body: options.body']
            ts += [f'    return this.#client._platform.call<T.{response}>("{name}", {{ {", ".join(params_ts)} }}, options);', '  }']
        ts += ['}']
        write(destination / f'python/fi/{directory}/_async_client.py', '\n'.join(py) + '\n')
        write(destination / f'typescript/futureagi/src/{directory}/client.ts', '\n'.join(ts) + '\n')


if __name__ == '__main__':
    main()
