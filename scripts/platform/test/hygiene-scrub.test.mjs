import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { test } from "node:test";
import { sha256 } from "../hygiene-names.mjs";
import { loadRules } from "../hygiene-scan.mjs";
import { applyMap, planMap } from "../hygiene-scrub.mjs";
import { loadTreeRules } from "../hygiene-tree.mjs";

const platform = loadRules();
const ID = ["U", 29].join("");
const DOC = "zz-design-notes";
const tree = { ...loadTreeRules(), binaries: [], exemptions: [], shas: { ...loadTreeRules().shas, reviewed: [] }, names: { maxWords: 4, sha256: { [sha256(DOC)]: "internal-doc" } } };

function repo(files) {
  const dir = mkdtempSync(path.join(tmpdir(), "hygiene-scrub-"));
  const git = (...args) =>
    execFileSync("git", ["-c", "user.name=t", "-c", "user.email=t@example.com", "-c", "commit.gpgsign=false", ...args], {
      cwd: dir,
      encoding: "utf8",
      env: { ...process.env, GIT_CONFIG_GLOBAL: "/dev/null", GIT_CONFIG_NOSYSTEM: "1" }
    });
  git("init", "-q");
  for (const [rel, content] of Object.entries(files)) {
    mkdirSync(path.dirname(path.join(dir, rel)), { recursive: true });
    writeFileSync(path.join(dir, rel), content);
  }
  git("add", "-A");
  git("commit", "-q", "-m", "base");
  return dir;
}

const A = [
  `"""The core (${DOC} section 2): shared, private."""`,
  "",
  `# built in ${ID}`,
  "x = 1",
  `# built in ${ID}`,
  `# see the ${DOC}`,
  ""
].join("\n");

function setup() {
  const dir = repo({ "python/fi/a.py": A, "python/fi/generated/g.py": `# ${ID}\n` });
  const map = planMap("HEAD", { cwd: dir, platform, tree, localOnly: [] });
  return { dir, map, entry: (line) => map.entries.find((e) => e.path === "python/fi/a.py" && e.line === line) };
}

test("--plan lists each line with a hit once, with its whole text, and marks generated files", () => {
  const { map } = setup();
  assert.deepEqual(
    map.entries.map((e) => `${e.path}:${e.line} ${e.rules.join(",")} ${e.generated}`),
    ["python/fi/a.py:1 internal-doc false", "python/fi/a.py:3 stream-id false", "python/fi/a.py:5 stream-id false", "python/fi/a.py:6 internal-doc false", "python/fi/generated/g.py:1 stream-id true"]
  );
  assert.equal(map.entries[1].text, `# built in ${ID}`);
  assert.ok(map.entries.every((e) => e.replace === null));
  assert.equal(map.findings.length, 0);
});

test("--apply rewrites every line equal to an entry's text, deletes, splits, and writes nothing on --check", () => {
  const { dir, map, entry } = setup();
  entry(1).replace = '"""The core: shared, private."""';
  entry(3).replace = "# built for the platform core";
  entry(6).replace = "# see CONVENTIONS.md\n# for the module rules";
  const file = path.join(dir, "python/fi/a.py");
  const checked = applyMap(map, { root: dir, check: true, platform, tree });
  assert.deepEqual(checked.problems, []);
  assert.equal(readFileSync(file, "utf8"), A, "--check writes nothing");
  const done = applyMap(map, { root: dir, platform, tree });
  assert.deepEqual(done, { problems: [], applied: 3, files: 1 });
  assert.equal(
    readFileSync(file, "utf8"),
    ['"""The core: shared, private."""', "", "# built for the platform core", "x = 1", "# built for the platform core", "# see CONVENTIONS.md", "# for the module rules", ""].join("\n")
  );
  const deleting = { entries: [{ path: "python/fi/a.py", line: 4, text: "x = 1", delete: true }] };
  assert.equal(applyMap(deleting, { root: dir, platform, tree }).applied, 1);
  assert.ok(!readFileSync(file, "utf8").includes("x = 1"));
});

test("--apply refuses stale entries, generated files and new lines that still hit, and then writes nothing", () => {
  const { dir, map, entry } = setup();
  const file = path.join(dir, "python/fi/a.py");
  entry(3).replace = `# still ${ID}`;
  entry(6).replace = "# fine";
  map.entries.find((e) => e.generated).replace = "# regenerated by hand";
  map.entries.push({ path: "python/fi/a.py", line: 9, text: "# gone", replace: "# x" });
  map.entries.push({ path: "python/fi/missing.py", line: 1, text: "# x", replace: "# y" });
  const { problems, applied } = applyMap(map, { root: dir, platform, tree });
  assert.equal(applied, 2);
  assert.deepEqual(
    problems.map((p) => p.replace(/: .*?(stale|generated|still hits|not in the working tree).*/u, ": $1")),
    ["python/fi/a.py:3: still hits", "python/fi/generated/g.py:1: generated", "python/fi/a.py:9: stale", "python/fi/missing.py:1: not in the working tree"]
  );
  assert.equal(readFileSync(file, "utf8"), A, "nothing is written while any entry fails");
});
