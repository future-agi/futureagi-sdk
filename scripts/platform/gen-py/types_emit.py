#!/usr/bin/env python3
"""Emit ``python/fi/generated/platform/types.py`` from the scoped platform contract.

    python3 scripts/platform/gen-py/types_emit.py            # write the module
    python3 scripts/platform/gen-py/types_emit.py --out DIR  # write into DIR instead (regenerate-and-diff)

``scripts/generate-platform-sdk.sh`` runs this, then formats the output with the pinned black;
``scripts/platform/check.sh`` regenerates into a temporary directory the same way and diffs.

One ``TypedDict`` or type alias per titled schema of
``openapi/platform/generated/futureagi-platform.openapi.json``. The rules:

- the public name is the schema's ``title`` (every component has one), so adding a schema never renames
  a type; the platform namespaces re-export the names they promise;
- responses are forward compatible: every ``TypedDict`` is ``total=False`` (a field a newer server adds,
  or one an older server leaves out, never breaks a type check of code that reads what it needs), and
  every string enum is open: ``Literal["a", "b"] | str``;
- inline (untitled) objects are ``dict[str, Any]``: they are not public types;
- a property that is not a plain Python identifier (``from``, ``x-y``, ``__z``) makes its class use the
  functional syntax.

Standard library only; the output imports only ``typing`` and runs on Python 3.10 and later.
"""

from __future__ import annotations

import argparse
import json
import keyword
import sys
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parents[3]
SPEC = REPO / "openapi" / "platform" / "generated" / "futureagi-platform.openapi.json"
OUT = REPO / "python" / "fi" / "generated" / "platform" / "types.py"
HEADER = (
    "# GENERATED by scripts/platform/gen-py/types_emit.py from "
    "openapi/platform/generated/futureagi-platform.openapi.json. Do not edit.\n"
)
PRIMITIVES = {
    "string": "str",
    "integer": "int",
    "number": "float",
    "boolean": "bool",
    "null": "None",
}


def _ref_name(ref: str, schemas: dict[str, Any]) -> str:
    key = ref.rsplit("/", 1)[-1]
    return str(schemas[key].get("title") or key)


def _literal(values: list[Any]) -> str:
    return "Literal[" + ", ".join(repr(v) for v in values) + "]"


def _union(parts: list[str]) -> str:
    out: list[str] = []
    for part in parts:
        for piece in part.split(" | "):
            if piece not in out:
                out.append(piece)
    if "Any" in out:
        return "Any"
    return " | ".join(out)


def annotate(node: Any, schemas: dict[str, Any], *, quoted: bool = False) -> str:
    """A type annotation for one schema node (``quoted`` writes refs as strings, for aliases)."""
    if not isinstance(node, dict):
        return "Any"
    if "$ref" in node:
        name = _ref_name(node["$ref"], schemas)
        return repr(name) if quoted else name
    for key in ("oneOf", "anyOf"):
        if key in node:
            return _union(
                [annotate(branch, schemas, quoted=quoted) for branch in node[key]]
            )
    if "allOf" in node and len(node["allOf"]) == 1:
        return annotate(node["allOf"][0], schemas, quoted=quoted)
    if "const" in node:
        if isinstance(node["const"], str):
            return _union([_literal([node["const"]]), "str"])
        return _literal([node["const"]])
    if "enum" in node:
        strings = all(isinstance(v, str) for v in node["enum"] if v is not None)
        lit = _literal([v for v in node["enum"] if v is not None])
        parts = [lit, "str"] if strings else [lit]
        if None in node["enum"]:
            parts.append("None")
        return _union(parts)
    kinds = node.get("type")
    if isinstance(kinds, list):
        return _union(
            [annotate({**node, "type": k}, schemas, quoted=quoted) for k in kinds]
        )
    if kinds == "array":
        return f"list[{annotate(node.get('items'), schemas, quoted=quoted)}]"
    if kinds == "object":
        extra = node.get("additionalProperties")
        if isinstance(extra, dict) and not node.get("properties"):
            return f"dict[str, {annotate(extra, schemas, quoted=quoted)}]"
        return "dict[str, Any]"
    if isinstance(kinds, str) and kinds in PRIMITIVES:
        return PRIMITIVES[kinds]
    return "Any"


def _doc(text: str | None, fallback: str) -> str:
    one = " ".join((text or fallback).split())
    return one.replace("\\", "\\\\").replace('"""', "'''")


def _comment(text: str | None) -> list[str]:
    if not text:
        return []
    return ["    #: " + " ".join(text.split())[:200]]


def _object_parts(
    node: dict[str, Any], schemas: dict[str, Any]
) -> tuple[list[str], dict[str, Any]]:
    """The base classes (titled ``allOf`` refs) and own properties of an object schema."""
    bases: list[str] = []
    props: dict[str, Any] = dict(node.get("properties") or {})
    for branch in node.get("allOf", []):
        if "$ref" in branch:
            bases.append(_ref_name(branch["$ref"], schemas))
        elif isinstance(branch, dict):
            props.update(branch.get("properties") or {})
    return bases, props


def _is_object(node: dict[str, Any]) -> bool:
    if node.get("type") == "object" and (
        node.get("properties") or not node.get("additionalProperties")
    ):
        return True
    return "allOf" in node and any("$ref" in b for b in node["allOf"])


def _plain_field(name: str) -> bool:
    return (
        name.isidentifier()
        and not keyword.iskeyword(name)
        and not name.startswith("__")
    )


def _ordered(schemas: dict[str, Any]) -> list[tuple[str, Any]]:
    """Schemas by title, except that a class's ``allOf`` bases come before it."""
    by_title = sorted(
        schemas.items(), key=lambda item: str(item[1].get("title") or item[0])
    )
    done: set[str] = set()
    out: list[tuple[str, Any]] = []

    def visit(key: str, node: Any) -> None:
        if key in done:
            return
        done.add(key)
        for branch in node.get("allOf", []) if isinstance(node, dict) else []:
            if isinstance(branch, dict) and "$ref" in branch:
                base = branch["$ref"].rsplit("/", 1)[-1]
                visit(base, schemas[base])
        out.append((key, node))

    for key, node in by_title:
        visit(key, node)
    return out


def _alias(node: dict[str, Any], schemas: dict[str, Any]) -> str:
    text = annotate(node, schemas, quoted=True)
    if " | " in text and "'" in text:
        return "Union[" + ", ".join(text.split(" | ")) + "]"
    return text


def emit_types(schemas: dict[str, Any]) -> str:
    """The text of ``fi/generated/platform/types.py``."""
    classes: list[str] = []
    aliases: list[str] = []
    names: list[str] = []
    for key, node in _ordered(schemas):
        title = str(node.get("title") or key)
        if not title.isidentifier() or keyword.iskeyword(title):
            raise SystemExit(
                f"schema {key}: title {title!r} is not a Python identifier"
            )
        if title in names:
            raise SystemExit(f"schema {key}: title {title!r} is used twice")
        names.append(title)
        doc = _doc(
            node.get("description"), f"The ``{title}`` schema of the platform contract."
        )
        if _is_object(node):
            bases, props = _object_parts(node, schemas)
            if all(_plain_field(name) for name in props):
                lines = [
                    f"class {title}({', '.join(bases) or 'TypedDict'}, total=False):",
                    f'    """{doc}"""',
                    "",
                ]
                for name, value in props.items():
                    lines += _comment(
                        value.get("description") if isinstance(value, dict) else None
                    )
                    lines.append(f"    {name}: {annotate(value, schemas)}")
                classes.append("\n".join(lines).rstrip())
            else:
                quoted = {
                    name: annotate(value, schemas, quoted=True)
                    for name, value in props.items()
                }
                body = ", ".join(f"{name!r}: {value}" for name, value in quoted.items())
                aliases.append(
                    f"#: {doc}\n{title} = TypedDict({title!r}, {{{body}}}, total=False)\n{title}.__doc__ = {doc!r}"
                )
        else:
            aliases.append(f"#: {doc}\n{title}: TypeAlias = {_alias(node, schemas)}")
    head = [
        HEADER.rstrip(),
        '"""Every titled schema of the platform contract, as a ``TypedDict`` or an alias. Private: import',
        'public types from the corresponding admitted platform namespaces."""',
        "",
        "from __future__ import annotations",
        "",
        "from typing import Any, Literal, TypeAlias, TypedDict, Union",
        "",
        "#: Every type this module defines, by contract title.",
        "TITLES: tuple[str, ...] = (",
        *[f"    {n!r}," for n in names],
        ")",
    ]
    return (
        "\n".join(head)
        + "\n\n\n"
        + "\n\n\n".join(classes)
        + "\n\n\n"
        + "\n\n".join(aliases)
        + "\n"
    )


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument(
        "--spec", type=Path, default=SPEC, help="the scoped OpenAPI file"
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=None,
        help="write types.py into this directory instead",
    )
    args = parser.parse_args(argv)
    spec = json.loads(args.spec.read_text(encoding="utf-8"))
    text = emit_types(spec["components"]["schemas"])
    target = (args.out / "types.py") if args.out else OUT
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
