#!/usr/bin/env node
/**
 * The one policy emitter for both languages.
 *
 *   node scripts/platform/emit-policy.mjs            # write both modules
 *   node scripts/platform/emit-policy.mjs --out DIR  # write both into DIR (regenerate-and-diff)
 *
 * Reads `openapi/platform/generated/futureagi-platform.openapi.json` and `openapi/platform/source.json`,
 * and writes `python/fi/generated/platform/policy.py` and
 * `typescript/futureagi/src/generated/platform/policy.gen.ts`: the operation table in the platform core's
 * own types (`fi._core.policy.OperationSpec`; `OperationTable` in `src/_core/policy.ts`; the field
 * mapping is `policy-shape.mjs`), so the executor in each language reads it as it is. The TypeScript
 * table is checked with `satisfies OperationTable`, so a field the core does not declare fails `tsc`.
 * `scripts/generate-platform-sdk.sh` formats the Python module with the pinned black;
 * `scripts/platform/check.sh` regenerates and diffs both.
 */

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { buildPolicy, policyCounts } from "./policy-model.mjs";
import { sourceProvenance } from "./source-pin.mjs";
import { extrasEntry, PAGINATION_FIELDS, runtimeEntry, STREAM_FIELDS, tsEntry, tsExtrasEntry, tsValue } from "./policy-shape.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const SPEC = "openapi/platform/generated/futureagi-platform.openapi.json";
export const PY_OUT = "python/fi/generated/platform/policy.py";
export const TS_OUT = "typescript/futureagi/src/generated/platform/policy.gen.ts";
const BANNER = `GENERATED by scripts/platform/emit-policy.mjs from ${SPEC}. Do not edit.`;

/** A Python literal for a JSON value (arrays become tuples, so the table is immutable data). */
export function pyLiteral(value) {
  if (value === null) return "None";
  if (value === true) return "True";
  if (value === false) return "False";
  if (typeof value === "number") return String(value);
  if (typeof value === "string") return JSON.stringify(value);
  if (Array.isArray(value)) return value.length === 0 ? "()" : `(${value.map(pyLiteral).join(", ")}${value.length === 1 ? "," : ""})`;
  return `{${Object.entries(value)
    .map(([k, v]) => `${JSON.stringify(k)}: ${pyLiteral(v)}`)
    .join(", ")}}`;
}

/** A keyword call, `Fn(a=1, b=None)`, with the fields in the given order. */
function pyCall(fn, value, fields, nested = {}) {
  const args = fields.map((f) => `${f}=${value[f] !== null && nested[f] ? nested[f](value[f]) : pyLiteral(value[f])}`);
  return `${fn}(${args.join(", ")})`;
}

/** One `Op(...)` (`OperationSpec`) constructor call for a model entry, every field written. */
export function pyOperation(entry) {
  const runtime = runtimeEntry(entry);
  return pyCall("Op", runtime, Object.keys(runtime), {
    stream: (s) => pyCall("Stream", s, STREAM_FIELDS),
    pagination: (p) => pyCall("Page", p, PAGINATION_FIELDS)
  });
}

function contractBlock(source, operations) {
  return {
    ...sourceProvenance(source),
    scoped_sha256: source.scoped.sha256,
    operation_count: operations.length,
    counts: policyCounts(operations)
  };
}

export function renderPython({ operations, events }, source) {
  const extras = operations.map((op) => [op.name, extrasEntry(op)]).filter(([, e]) => Object.keys(e).length > 0);
  const lines = [
    `# ${BANNER}`,
    '"""The platform operation table: one ``OperationSpec`` per wrapped operation, by SDK name.',
    "",
    "The platform client looks an operation up here by name (``<family>.<method>``) and builds the request",
    "from it: the method, the path template, the declared query keys and headers, and the body class.",
    "``fi._core.policy`` derives each operation's retry class (``keyed``, ``keyed-not-durable``,",
    "``http-idempotent``, ``unsafe``) from ``idempotent``, ``durable`` and the method. ``durable`` is False",
    "only where the contract states ``durable: false``. ``EXTRAS`` holds the contract facts that",
    "``OperationSpec`` does not carry.",
    '"""',
    "",
    "from __future__ import annotations",
    "",
    "from typing import Any",
    "",
    "from fi._core.policy import OperationSpec as Op",
    "from fi._core.policy import PaginationSpec as Page",
    "from fi._core.policy import StreamSpec as Stream",
    "",
    "#: Where this table came from, and its counts.",
    `CONTRACT: dict[str, Any] = ${pyLiteral(contractBlock(source, operations))}`,
    "",
    "#: Every wrapped operation, by SDK name.",
    "OPERATIONS: dict[str, Op] = {"
  ];
  for (const op of operations) lines.push(`    ${JSON.stringify(op.name)}: ${pyOperation(op)},`);
  lines.push(
    "}",
    "",
    "#: Contract facts ``OperationSpec`` does not carry, by SDK name: ``replay_omits`` (response fields a",
    "#: replayed call leaves out), ``resume_when`` (which stream lines resume), ``opaque_cursor``, ``stop``",
    "#: (a verb that stops work) and ``durable_unstated`` (an idempotent operation whose contract does not",
    "#: state durability; ``OperationSpec.durable`` is True for it).",
    `EXTRAS: dict[str, dict[str, Any]] = ${pyLiteral(Object.fromEntries(extras))}`,
    "",
    "#: The event types each stream knows, per frame union; any other type is an unknown event.",
    `KNOWN_EVENTS: dict[str, tuple[str, ...]] = ${pyLiteral(events)}`,
    ""
  );
  return lines.join("\n");
}

export function renderTypeScript({ operations, events }, source) {
  const lines = [
    `// ${BANNER}`,
    "/* eslint-disable */",
    "",
    "/**",
    " * The platform operation table: one `OperationSpec` per wrapped operation, by SDK name",
    " * (`<family>.<method>`), in the platform core's own type. `src/_core/policy.ts` derives each",
    " * operation's retry class from `idempotent`, `durable` and the method; `durable` is false only where",
    " * the contract states `durable: false`. `PLATFORM_OPERATION_EXTRAS` holds the contract facts that",
    " * `OperationSpec` does not carry.",
    " */",
    "",
    'import type { OperationTable } from "../../_core/policy";',
    "",
    "/** Where this table came from, and its counts. */",
    `export const PLATFORM_CONTRACT = ${JSON.stringify(tsValue(contractBlock(source, operations)))} as const;`,
    "",
    "/** Every wrapped operation, by SDK name. */",
    "export const PLATFORM_OPERATIONS = {"
  ];
  for (const op of operations) lines.push(`  ${JSON.stringify(op.name)}: ${JSON.stringify(tsEntry(op))},`);
  lines.push(
    "} as const satisfies OperationTable;",
    "",
    "/** An SDK operation name. */",
    "export type PlatformOperationName = keyof typeof PLATFORM_OPERATIONS;",
    "",
    "/**",
    " * Contract facts `OperationSpec` does not carry: the timeout, rate and role classes, the response fields",
    " * a replayed call leaves out, which stream lines resume, an opaque cursor, a verb that stops work, and an",
    " * idempotent operation whose contract does not state durability (`durable` is true for it).",
    " */",
    "export interface PlatformOperationExtras {",
    '  readonly timeout: "read" | "write" | "model" | "stream";',
    '  readonly rate?: "read" | "write" | "model-start";',
    "  readonly role?: string;",
    "  readonly replayOmits?: readonly string[];",
    "  readonly resumeWhen?: string;",
    "  readonly opaqueCursor?: boolean;",
    "  readonly stop?: boolean;",
    "  readonly durableUnstated?: boolean;",
    "}",
    "",
    "/** The extras of every operation, by SDK name. */",
    "export const PLATFORM_OPERATION_EXTRAS = {"
  );
  for (const op of operations) lines.push(`  ${JSON.stringify(op.name)}: ${JSON.stringify(tsExtrasEntry(op))},`);
  lines.push(
    "} as const satisfies Record<PlatformOperationName, PlatformOperationExtras>;",
    "",
    "/** The event types each stream knows, per frame union; any other type is an unknown event. */",
    `export const PLATFORM_KNOWN_EVENTS = ${JSON.stringify(events)} as const;`,
    ""
  );
  return lines.join("\n");
}

export function renderAll(root = ROOT) {
  const doc = JSON.parse(readFileSync(path.join(root, SPEC), "utf8"));
  const source = JSON.parse(readFileSync(path.join(root, "openapi/platform/source.json"), "utf8"));
  const policy = buildPolicy(doc);
  return { [PY_OUT]: renderPython(policy, source), [TS_OUT]: renderTypeScript(policy, source) };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const ok = args.length === 0 || (args.length === 2 && args[0] === "--out");
  if (!ok) {
    process.stderr.write("usage: emit-policy.mjs [--out DIR]\n");
    process.exit(2);
  }
  const outDir = args.length === 2 ? path.resolve(args[1]) : undefined;
  for (const [rel, text] of Object.entries(renderAll())) {
    const target = outDir ? path.join(outDir, path.basename(rel)) : path.join(ROOT, rel);
    mkdirSync(path.dirname(target), { recursive: true });
    writeFileSync(target, text);
  }
}
