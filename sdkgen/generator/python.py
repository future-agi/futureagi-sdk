def top_level(ops: list[Op]) -> list[tuple[str, ...]]:
    return sorted(ns for ns in namespace_tree(ops) if len(ns) == 1)


def emit_resource_index(ops: list[Op]) -> str:
    roots = top_level(ops)
    out = [
        HEADER,
        '"""What `Client` and `AsyncClient` expose: one hand-written class per top-level resource.\n\n',
        "Each module in this package is scaffolded once by the generator and then owned by hand.\n",
        "To swap a class, subclass the client and override `_resources`:\n\n",
        "    class MyClient(Client):\n",
        '        _resources = {**Client._resources, "datasets": MyDatasets}\n',
        '"""\n\n',
        "from __future__ import annotations\n\n",
        "from typing import Dict\n\n",
        "from .._resource import ResourceSet\n",
    ]
    for ns in roots:
        out.append(f"from .{ns[0]} import {', '.join(sorted([public_class(ns, is_async=False), public_class(ns, is_async=True)]))}\n")
    for is_async in (False, True):
        prefix = "Async" if is_async else ""
        out.append(f"\n\nclass {prefix}Resources(ResourceSet):\n")
        out.append(f'    """Mixed into {prefix}Client: one attribute per top-level resource."""\n\n')
        for ns in roots:
            out.append(f"    {ns[0]}: {public_class(ns, is_async=is_async)}\n")
        mapping = ", ".join(f"{ns[0]!r}: {public_class(ns, is_async=is_async)}" for ns in roots)
        out.append(f"    _resources: Dict[str, type] = {{{mapping}}}\n")
    out.append("\n\n__all__ = [\n    'AsyncResources',\n    'Resources',\n")
    for is_async in (False, True):
        for ns in roots:
            out.append(f"    {public_class(ns, is_async=is_async)!r},\n")
    out.append("]\n")
    return "".join(out)


def scaffold_docstrings(ns: tuple[str, ...]) -> tuple[str, str]:
    """Class docstrings of the (sync, async) scaffold: the reference pages show them as the summary."""
    attr = ns[0]
    return (
        f"`client.{attr}`: every generated `{attr}.*` method, plus the hand-written additions in this module.",
        f"`client.{attr}` for `AsyncClient`: the same methods as `{public_class(ns, is_async=False)}`, awaited.",
    )


def scaffold_resource(ns: tuple[str, ...]) -> str:
    sync_cls, async_cls = generated_class(ns, is_async=False), generated_class(ns, is_async=True)
    sync_doc, async_doc = scaffold_docstrings(ns)
    return (
        f'"""Hand-written additions to `client.{ns[0]}`.\n\n'
        "Scaffolded once by sdkgen/generate.py and never overwritten: methods added here survive\n"
        "regeneration. The generated methods live in `fi.platform.resources.base`.\n\n"
        "    class Datasets(DatasetsResource):\n"
        "        def get_by_name(self, name: str):\n"
        "            ...                                     # compose generated methods, or\n"
        '            return self._t.raw("GET", "/some/path/")  # call an endpoint the catalog lacks\n'
        '"""\n\n'
        "from __future__ import annotations\n\n"
        f"from .base import {', '.join(sorted([async_cls, sync_cls]))}\n\n\n"
        f'class {public_class(ns, is_async=False)}({sync_cls}):\n    """{sync_doc}"""\n\n\n'
        f'class {public_class(ns, is_async=True)}({async_cls}):\n    """{async_doc}"""\n'
    )
