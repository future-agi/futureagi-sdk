"""Python emitter: pydantic models, resource classes, and the hand-written extension points.

Generated (overwritten on every run)
    python/fi/platform/models.py                  response models (public, `fi.platform.models`)
    python/fi/platform/_operations.py             one `Operation` per call (method, path, unwrap, pagination)
    python/fi/platform/resources/base.py          <Name>Resource / Async<Name>Resource classes (public, documented)
    python/fi/platform/resources/__init__.py      the Resources mixins the clients inherit

Scaffolded (written once, then owned by hand)
    python/fi/platform/resources/<name>.py        `class Datasets(DatasetsResource)`: add your own methods here
"""

from __future__ import annotations

import keyword
import re

from .catalog import (
    CatalogError,
    Op,
    Param,
    children_of,
    class_name,
    is_file,
    is_method_field,
    model_refs,
    namespace_tree,
    sdk_ops,
)

HEADER = "# Generated by sdkgen/generate.py from sdkgen/contracts/swagger.json + sdkgen/catalog/operations.yaml. Do not edit.\n"

_BASEMODEL_ATTRS = {"copy", "dict", "json", "schema", "construct", "validate", "fields", "model_config"}
_RESERVED_METHODS = {"request"}  # hand-written Client/Resource attributes a generated method must not shadow


def field_name(name: str) -> str:
    safe = re.sub(r"\W", "_", name)
    if keyword.iskeyword(safe) or safe in _BASEMODEL_ATTRS or safe[0].isdigit():
        safe = f"{safe}_"
    return safe


def arg_name(p: Param) -> str:
    return p.arg_name or field_name(p.name)


def camel(parts: tuple[str, ...] | list[str]) -> str:
    return "".join(p.title().replace("_", "") for p in parts)


def generated_class(ns: tuple[str, ...], *, is_async: bool) -> str:
    return f"{'Async' if is_async else ''}{camel(ns)}Resource"


def public_class(ns: tuple[str, ...], *, is_async: bool) -> str:
    """The hand-written subclass users see (`Datasets`, `AsyncDatasets`)."""
    return f"{'Async' if is_async else ''}{camel(ns)}"


def py39(annotation: str) -> str:
    """`list[X]` / `dict[K, V]` -> `List[X]` / `Dict[K, V]` so models import on Python 3.9."""
    return re.sub(r"\b(list|dict)\[", lambda m: m.group(1).title() + "[", annotation)


def py_type(schema: dict | None, *, for_input: bool) -> str:
    if not schema:
        return "Any"
    if for_input and schema.get("type") == "file":
        return "FileInput"
    if "$ref" in schema:
        return "dict[str, Any]" if for_input else class_name(schema["$ref"])
    if "enum" in schema:
        # Inputs are strict; outputs accept unknown values so a new server enum never crashes a client.
        return "Literal[" + ", ".join(repr(v) for v in schema["enum"]) + "]" if for_input else "str"
    kind = schema.get("type")
    if kind == "array":
        item = py_type(schema.get("items"), for_input=for_input)
        # Output list items may be null even when the contract says they aren't (seen live).
        return f"list[{item}]" if for_input else f"list[Optional[{item}]]"
    if kind == "object" and not for_input and not schema.get("properties"):
        return "Any"  # free-form JSON: seen live as lists and scalars where the contract says object
    return {"string": "str", "integer": "int", "number": "float", "boolean": "bool", "object": "dict[str, Any]", "file": "bytes"}.get(kind, "Any")


