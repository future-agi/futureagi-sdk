def op_constant(op: Op) -> str:
    return "OP_" + op.id.upper().replace(".", "_")


def emit_operations(ops: list[Op]) -> str:
    out = [
        HEADER,
        '"""One `Operation` per generated call: method, path, response envelope key, pagination."""\n\n',
        "from ._transport import Operation\n\n",
    ]
    for op in sdk_ops(ops):
        spec = {"id": op.id, "method": op.method, "path": op.path, "unwrap": op.unwrap, "pagination": op.pagination}
        if op.multipart:
            spec["multipart"] = True
        if op.decode != "json":
            spec["decode"] = op.decode
        out.append(f"{op_constant(op)} = Operation(**{spec!r})\n")
    return "".join(out)


def _return_annotation(op: Op, *, is_async: bool) -> tuple[str, str | None]:
    """(annotation, runtime type to validate the response with)."""
    returns = op.returns or {}
    if "$ref" in returns:
        item = model = f"models.{class_name(returns['$ref'])}"
    elif returns.get("type") == "array" and "$ref" in returns.get("items", {}):
        inner = f"models.{class_name(returns['items']['$ref'])}"
        item = model = f"List[{inner}]"
    else:
        item, model = py_type(op.returns, for_input=False), None
    if op.pagination:
        return (f"AsyncPager[{item}]" if is_async else f"SyncPager[{item}]"), model
    if op.decode == "text":
        return "str", None
    if op.decode == "auto":
        return "Any", None  # JSON when the response is JSON, else the body text
    if op.returns is None:
        return "Any", None  # the contract does not describe the response
    return item, model


def _signature(op: Op) -> tuple[list[str], list[tuple[Param, str]]]:
    """Positional path params, then keyword-only body/query params (required first), then escape hatches."""
    page_params = {op.pagination["page_param"]} if op.pagination else set()  # the pager owns the page cursor
    args = ["self"]
    rest = [p for p in op.params if p.location != "path" and p.name not in page_params]
    rest.sort(key=lambda p: not p.required)
    named: list[tuple[Param, str]] = []
    for p in op.params_in("path"):
        args.append(f"{arg_name(p)}: str")
        named.append((p, arg_name(p)))
    args.append("*")
    for p in rest:
        py = py_type(p.schema, for_input=True)
        # Optional: NOT_GIVEN is left out of the request, an explicit None is sent as null.
        args.append(f"{arg_name(p)}: {py}" if p.required else f"{arg_name(p)}: {py} | None | NotGiven = NOT_GIVEN")
        named.append((p, arg_name(p)))
    # Escape hatches: fields the contract does not (yet) describe, and per-call request options.
    args.append("extra_query: dict[str, Any] | None = None")
    if op.sends_body:
        args.append("extra_body: dict[str, Any] | None = None")
    args.append("options: RequestOptions | None = None")
    return args, named


def _method(op: Op, *, is_async: bool) -> str:
    if op.method_name in _RESERVED_METHODS:
        raise CatalogError(f"{op.id}: method name {op.method_name!r} is reserved by the hand-written client")
    args, named = _signature(op)
    ret, model = _return_annotation(op, is_async=is_async)
    stability = op.surfaces["sdk"]["stability"]
    lines = [f"    {'async ' if is_async and not op.pagination else ''}def {op.method_name}({', '.join(args)}) -> {ret}:\n"]
    doc = op.description + (f"\n\n        .. {stability}:: this method may change without notice." if stability == "beta" else "")
    lines.append(f'        """{doc}\n\n        {op.method} {op.path}\n        """\n')
    if stability != "stable":
        lines.append(f"        _stability({op.id!r}, {stability!r})\n")
    for location in ("path", "query", "body") if op.sends_body else ("path", "query"):
        group = [(p, a) for p, a in named if p.location == location and not (location == "body" and is_file(p.schema))]
        items = ", ".join(f"{p.name!r}: {a}" for p, a in group)
        if location in ("query", "body"):
            items = f"{items}, **(extra_{location} or {{}})".lstrip(", ")
        lines.append(f"        {location} = {{{items}}}\n" if items else f"        {location} = None\n")
    if not op.sends_body and not op.pagination:
        lines.append("        body = None\n")
    if op.multipart:  # file params travel separately from the form fields
        uploads = ", ".join(f"{p.name!r}: {a}" for p, a in named if p.location == "body" and is_file(p.schema))
        lines.append(f"        files = {{{uploads}}}\n")
    model_arg = model or "None"
    if op.pagination:
        fn = "apaginate" if is_async else "paginate"
        lines.append(f"        return self._t.{fn}(_ops.{op_constant(op)}, path=path, query=query, model={model_arg}, options=options)\n")
    else:
        prefix = "await self._t.acall" if is_async else "self._t.call"
        files_arg = ", files=files" if op.multipart else ""
        lines.append(f"        return {prefix}(_ops.{op_constant(op)}, path=path, query=query, body=body{files_arg}, model={model_arg}, options=options)\n")
    return "".join(lines)


def _resource_class(tree, ns: tuple[str, ...], *, is_async: bool) -> str:
    cls = generated_class(ns, is_async=is_async)
    transport = "AsyncTransport" if is_async else "SyncTransport"
    children = children_of(tree, ns)
    out = [f"\n\nclass {cls}(Resource):\n"]
    out.append(f'    """`client.{".".join(ns)}`. Subclass to add methods; override `_children` to swap a nested resource."""\n\n')
    out.append(f"    _t: {transport}\n")
    for child in children:
        out.append(f"    {child[-1]}: {generated_class(child, is_async=is_async)}\n")
    if children:
        mapping = ", ".join(f"{child[-1]!r}: {generated_class(child, is_async=is_async)}" for child in children)
        out.append(f"    _children: Dict[str, type] = {{{mapping}}}\n")
    for op in sorted(tree[ns], key=lambda o: o.method_name):
        out.append("\n" + _method(op, is_async=is_async))
    return "".join(out)


def emit_resources(ops: list[Op]) -> str:
    tree = namespace_tree(ops)
    out = [
        HEADER,
        '"""Resource base classes, one per catalog namespace: every generated method lives here.\n\n',
        "Names come from catalog ids, so they match the MCP tools. `Client` exposes the hand-written\n",
        "subclasses in `fi.platform.resources` (`Datasets(DatasetsResource)`); nested resources\n",
        "(`client.datasets.rows`) are these classes directly. Add custom methods to the subclasses,\n",
        'not here.\n"""\n\n',
        "from __future__ import annotations\n\n",
        "{typing}",
        "from .. import _operations as _ops\n",
        "from .. import models\n",
        "from .._pagination import AsyncPager, SyncPager\n",
        "from .._resource import Resource\n",
        "from .._stability import _stability\n",
        "from .._transport import (\n    NOT_GIVEN,\n    AsyncTransport,\n    FileInput,\n    NotGiven,\n    RequestOptions,\n    SyncTransport,\n)\n",
    ]
    for is_async in (False, True):
        for ns in sorted(tree, key=lambda ns: (-len(ns), ns)):  # children before parents
            out.append(_resource_class(tree, ns, is_async=is_async))
    out.append("\n\n__all__ = [\n")
    for is_async in (False, True):
        for ns in sorted(tree):
            out.append(f"    {generated_class(ns, is_async=is_async)!r},\n")
    out.append("]\n")
    # typing.List/Dict, not list[]/dict[]: inside a resource class `list` is the list() method
    text = py39("".join(out))
    body = text.split("{typing}", 1)[1]
    used = [name for name in ("Any", "Dict", "List", "Literal", "Optional") if re.search(rf"\b{name}\b", body)]
    return text.replace("{typing}", f"from typing import {', '.join(used)}\n\n", 1)


