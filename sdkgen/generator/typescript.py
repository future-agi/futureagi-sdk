"""TypeScript emitter: the same catalog as `client.<resource>.<method>()` for `@future-agi/sdk`.

Generated (overwritten on every run)
    typescript/futureagi/src/platform/models.ts                  response interfaces (public, `@future-agi/sdk/platform/models`)
    typescript/futureagi/src/platform/_operations.ts             one `Operation` per call
    typescript/futureagi/src/platform/resources/base.ts          <Name>Resource classes + params types (public, documented)
    typescript/futureagi/src/platform/resources/index.ts         what `Client` exposes

Scaffolded (written once, then owned by hand)
    typescript/futureagi/src/platform/resources/<name>.ts        `class Datasets extends DatasetsResource`

Naming: resources and methods are camelCase (`client.knowledgeBases.createFromFile`), request
fields keep their wire names so they match the API docs and the Python SDK one to one.
"""

from __future__ import annotations

import json
import re

from .catalog import (
    Op,
    Param,
    children_of,
    class_name,
    is_file,
    is_method_field,
    model_refs,
    namespace_tree,
    sdk_ops,
)
from .python import camel

HEADER = "// Generated by sdkgen/generate.py from sdkgen/contracts/swagger.json + sdkgen/catalog/operations.yaml. Do not edit.\n"

_IDENTIFIER = re.compile(r"^[A-Za-z_$][\w$]*$")
_RESERVED = {"delete", "default", "import", "export", "new", "class", "function", "return", "typeof", "in", "of", "var", "let", "const"}


def lower_camel(name: str) -> str:
    head, *rest = name.split("_")
    return head + camel(rest)


def ts_method(op: Op) -> str:
    return lower_camel(op.method_name)  # `delete` is a valid method name in TS


def ts_attr(part: str) -> str:
    return lower_camel(part)


def ts_class(ns: tuple[str, ...]) -> str:
    return f"{camel(ns)}Resource"


def ts_public_class(ns: tuple[str, ...]) -> str:
    return camel(ns)


def ts_params_type(op: Op) -> str:
    return f"{camel(op.namespace)}{camel([op.method_name])}Params"


def ts_arg(p: Param) -> str:
    name = lower_camel(p.arg_name or p.name)
    return f"{name}_" if name in _RESERVED else name


def prop_key(name: str) -> str:
    return name if _IDENTIFIER.match(name) else json.dumps(name)


def ts_type(schema: dict | None, *, for_input: bool) -> str:
    if not schema:
        return "unknown"
    if for_input and schema.get("type") == "file":
        return "FileInput"
    if "$ref" in schema:
        return "Record<string, unknown>" if for_input else f"models.{class_name(schema['$ref'])}"
    if "enum" in schema:
        # Inputs are strict; outputs accept unknown values so a new server enum never breaks a caller.
        return " | ".join(json.dumps(v) for v in schema["enum"]) if for_input else "string"
    kind = schema.get("type")
    if kind == "array":
        item = ts_type(schema.get("items"), for_input=for_input)
        # Output list items may be null even when the contract says they aren't (seen live).
        return f"Array<{item}>" if for_input else f"Array<{item} | null>"
    if kind == "object" and not for_input and not schema.get("properties"):
        return "unknown"  # free-form JSON: seen live as lists and scalars where the contract says object
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "object": "Record<string, unknown>", "file": "Uint8Array"}.get(kind, "unknown")


def _doc(lines: list[str], indent: str = "") -> str:
    body = "".join(f"{indent} * {line}\n" if line else f"{indent} *\n" for line in lines)
    return f"{indent}/**\n{body}{indent} */\n"


# --------------------------------------------------------------------------- #
# models.ts
# --------------------------------------------------------------------------- #


def emit_models(spec: dict, ops: list[Op]) -> str:
    names = model_refs(spec, [op.returns for op in sdk_ops(ops) if op.returns])
    out = [HEADER, "// Response models. Every field is optional so a missing or new field never breaks a call.\n\n"]
    for name in names:
        props = spec["definitions"][name].get("properties", {})
        out.append(f"export interface {name} {{\n")
        for prop_name, prop in props.items():
            ts = ("unknown[]" if prop.get("type") == "array" else "unknown") if is_method_field(prop) else ts_type(prop, for_input=False).replace("models.", "")
            comment = f" // one of: {', '.join(map(str, prop['enum']))}" if "enum" in prop else ""
            out.append(f"  {prop_key(prop_name)}?: {ts} | null;{comment}\n")
        out.append("}\n\n")
    return "".join(out).rstrip("\n") + "\n"


# --------------------------------------------------------------------------- #
# _operations.ts and resources/base.ts
# --------------------------------------------------------------------------- #


def op_constant(op: Op) -> str:
    return "OP_" + op.id.upper().replace(".", "_")


def emit_operations(ops: list[Op]) -> str:
    out = [
        HEADER,
        "// One `Operation` per generated call: method, path, response envelope key, pagination.\n\n",
        "import type { Operation } from \"./transport\";\n\n",
    ]
    for op in sdk_ops(ops):
        spec = {"id": op.id, "method": op.method, "path": op.path, "unwrap": op.unwrap, "pagination": op.pagination}
        if op.multipart:
            spec["multipart"] = True
        out.append(f"export const {op_constant(op)}: Operation = {json.dumps(spec)};\n")
    return "".join(out)


def _return_type(op: Op) -> str:
    returns = op.returns or {}
    if "$ref" in returns:
        item = f"models.{class_name(returns['$ref'])}"
    elif returns.get("type") == "array" and "$ref" in returns.get("items", {}):
        item = f"Array<models.{class_name(returns['items']['$ref'])}>"
    else:
        item = ts_type(op.returns, for_input=False)
    if op.pagination:
        return f"Pager<{item}>"
    return f"Promise<{item}>"


def _params_interface(op: Op) -> tuple[str, list[Param]]:
    """The `params` object type: every query/body field except the page cursor, required first."""
    page_params = {op.pagination["page_param"]} if op.pagination else set()
    fields = [p for p in op.params if p.location != "path" and p.name not in page_params]
    fields.sort(key=lambda p: not p.required)
    if not fields:
        return "", fields
    out = [f"export interface {ts_params_type(op)} {{\n"]
    for p in fields:
        desc = f"  /** {p.description} */\n" if p.description else ""
        out.append(f"{desc}  {prop_key(p.name)}{'' if p.required else '?'}: {ts_type(p.schema, for_input=True)};\n")
    out.append("}\n\n")
    return "".join(out), fields


def _method(op: Op, fields: list[Param]) -> str:
    path_params = op.params_in("path")
    args = [f"{ts_arg(p)}: string" for p in path_params]
    if fields:
        optional = "" if any(p.required for p in fields) else " = {}"
        args.append(f"params: {ts_params_type(op)}{optional}")
    args.append("options?: RequestOptions")
    stability = op.surfaces["sdk"]["stability"]
    doc = [op.description, "", f"{op.method} {op.path}"]
    if stability == "beta":
        doc.append("@beta this method may change without notice.")
    if stability == "deprecated":
        doc.append("@deprecated")
    lines = [_doc(doc, "  ")]
    lines.append(f"  {ts_method(op)}({', '.join(args)}): {_return_type(op)} {{\n")
    if stability != "stable":
        lines.append(f"    warnStability({json.dumps(op.id)}, {json.dumps(stability)});\n")
    path = ", ".join(f"{prop_key(p.name)}: {ts_arg(p)}" for p in path_params)
    parts = [f"path: {{ {path} }}" if path else "path: {}"]
    for location in ("query", "body") if op.sends_body else ("query",):
        group = [p for p in fields if p.location == location and not (location == "body" and is_file(p.schema))]
        items = ", ".join(f"{prop_key(p.name)}: params.{prop_key(p.name)}" if _IDENTIFIER.match(p.name) else f"{prop_key(p.name)}: params[{prop_key(p.name)}]" for p in group)
        parts.append(f"{location}: {{ {items} }}" if items else f"{location}: {{}}")
    if op.multipart:
        uploads = ", ".join(f"{prop_key(p.name)}: params.{prop_key(p.name)}" for p in fields if p.location == "body" and is_file(p.schema))
        parts.append(f"files: {{ {uploads} }}")
    call = "paginate" if op.pagination else "call"
    generic = _return_type(op)[len("Pager<") if op.pagination else len("Promise<") : -1]
    lines.append(f"    return this._t.{call}<{generic}>(ops.{op_constant(op)}, {{ {', '.join(parts)} }}, options);\n")
    lines.append("  }\n")
    return "".join(lines)


def _resource_class(tree, ns: tuple[str, ...]) -> str:
    children = children_of(tree, ns)
    out = [_doc([f"`client.{'.'.join(ts_attr(part) for part in ns)}`. Subclass to add methods; reassign a child in the constructor to swap it."])]
    out.append(f"export class {ts_class(ns)} extends Resource {{\n")
    for child in children:
        out.append(f"  {ts_attr(child[-1])}: {ts_class(child)};\n")
    if children:
        out.append("\n  constructor(transport: Transport) {\n    super(transport);\n")
        for child in children:
            out.append(f"    this.{ts_attr(child[-1])} = new {ts_class(child)}(transport);\n")
        out.append("  }\n")
    for op in sorted(tree[ns], key=lambda o: o.method_name):
        _, fields = _params_interface(op)
        out.append("\n" + _method(op, fields))
    out.append("}\n\n")
    return "".join(out)


def emit_resources(ops: list[Op]) -> str:
    tree = namespace_tree(ops)
    out = [
        HEADER,
        "// Resource base classes, one per catalog namespace: every generated method lives here, with\n",
        "// the `params` type of each method. Names come from catalog ids, so they match the Python SDK\n",
        "// and the MCP tools. `Client` exposes the hand-written subclasses in this folder\n",
        "// (`Datasets extends DatasetsResource`); nested resources (`client.datasets.rows`) are these\n",
        "// classes directly. Add custom methods to the subclasses, not here.\n\n",
        "/* eslint-disable @typescript-eslint/no-unused-vars */\n",
        "import * as ops from \"../_operations\";\n",
        "import type * as models from \"../models\";\n",
        "import { Pager } from \"../pagination\";\n",
        "import { Resource } from \"../resource\";\n",
        "import { warnStability } from \"../stability\";\n",
        "import type { FileInput, RequestOptions, Transport } from \"../transport\";\n\n",
    ]
    for ns in sorted(tree):
        for op in sorted(tree[ns], key=lambda o: o.method_name):
            out.append(_params_interface(op)[0])
    for ns in sorted(tree, key=lambda ns: (-len(ns), ns)):  # children before parents
        out.append(_resource_class(tree, ns))
    return "".join(out).rstrip("\n") + "\n"


# --------------------------------------------------------------------------- #
# resources/index.ts (generated) and resources/<name>.ts (scaffolded once)
# --------------------------------------------------------------------------- #


def top_level(ops: list[Op]) -> list[tuple[str, ...]]:
    return sorted(ns for ns in namespace_tree(ops) if len(ns) == 1)


def emit_resource_index(ops: list[Op]) -> str:
    roots = top_level(ops)
    out = [
        HEADER,
        "// What `Client` exposes: one hand-written class per top-level resource. Each module in this\n",
        "// folder is scaffolded once by the generator and then owned by hand. To swap a class, pass\n",
        "// `new Client({ resources: { datasets: MyDatasets } })`.\n\n",
        "import type { Transport } from \"../transport\";\n",
    ]
    for ns in roots:
        out.append(f"import {{ {ts_public_class(ns)} }} from \"./{ns[0]}\";\n")
    out.append("\n// The generated base classes (nested resources are these) and every method's `params` type.\nexport * from \"./base\";\n")
    out.append("\nexport interface Resources {\n")
    for ns in roots:
        out.append(f"  {ts_attr(ns[0])}: {ts_public_class(ns)};\n")
    out.append("}\n\n")
    out.append("export type ResourceClasses = { [K in keyof Resources]: new (transport: Transport) => Resources[K] };\n\n")
    out.append("export const DEFAULT_RESOURCES: ResourceClasses = {\n")
    for ns in roots:
        out.append(f"  {ts_attr(ns[0])}: {ts_public_class(ns)},\n")
    out.append("};\n\n")
    out.append(
        "export function createResources(transport: Transport, overrides: Partial<ResourceClasses> = {}): Resources {\n"
        "  const classes = { ...DEFAULT_RESOURCES, ...overrides };\n"
        "  const out: Record<string, unknown> = {};\n"
        "  for (const [name, cls] of Object.entries(classes)) {\n"
        "    out[name] = new cls(transport);\n"
        "  }\n"
        "  return out as unknown as Resources;\n"
        "}\n\n"
    )
    out.append("export {\n" + "".join(f"  {ts_public_class(ns)},\n" for ns in roots) + "};\n")
    return "".join(out)


def scaffold_doc(ns: tuple[str, ...]) -> str:
    """The scaffold class's JSDoc: the reference pages show it as the summary."""
    attr = ts_attr(ns[0])
    return f"`client.{attr}`: every generated `{attr}.*` method, plus the hand-written additions in this file."


def scaffold_resource(ns: tuple[str, ...]) -> str:
    return (
        f"// Hand-written additions to `client.{ts_attr(ns[0])}`.\n"
        "//\n"
        "// Scaffolded once by sdkgen/generate.py and never overwritten: methods added here survive\n"
        "// regeneration. The generated methods live in `./base`.\n"
        "//\n"
        "//   export class Datasets extends DatasetsResource {\n"
        "//     async getByName(name: string) {\n"
        "//       ...                                              // compose generated methods, or\n"
        '//       return this._t.raw("GET", "/some/path/", {});    // call an endpoint the catalog lacks\n'
        "//     }\n"
        "//   }\n\n"
        f"import {{ {ts_class(ns)} }} from \"./base\";\n\n"
        f"/** {scaffold_doc(ns)} */\n"
        f"export class {ts_public_class(ns)} extends {ts_class(ns)} {{}}\n"
    )
