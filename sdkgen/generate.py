_BASEMODEL_ATTRS = {"copy", "dict", "json", "schema", "construct", "validate", "fields", "model_config"}


def _field_name(name: str) -> str:
    safe = re.sub(r"\W", "_", name)
    if keyword.iskeyword(safe) or safe in _BASEMODEL_ATTRS or safe[0].isdigit():
        safe = f"{safe}_"
    return safe


def _class_name(ref: str) -> str:
    return ref.rsplit("/", 1)[-1]


def _py_type(schema: dict | None, *, for_input: bool) -> str:
    if not schema:
        return "Any"
    if "$ref" in schema:
        return "dict[str, Any]" if for_input else _class_name(schema["$ref"])
    if "enum" in schema:
        # Inputs are strict; outputs accept unknown values so a new server enum never crashes a client.
        return "Literal[" + ", ".join(repr(v) for v in schema["enum"]) + "]" if for_input else "str"
    kind = schema.get("type")
    if kind == "array":
        return f"list[{_py_type(schema.get('items'), for_input=for_input)}]"
    return {"string": "str", "integer": "int", "number": "float", "boolean": "bool", "object": "dict[str, Any]", "file": "bytes"}.get(kind, "Any")


def _py39(annotation: str) -> str:
    """`list[X]` / `dict[K, V]` -> `List[X]` / `Dict[K, V]` so models import on Python 3.9."""
    return re.sub(r"\b(list|dict)\[", lambda m: m.group(1).title() + "[", annotation)


def _model_refs(spec: dict, roots: list[dict]) -> list[str]:
    found: list[str] = []

    def visit(node: Any) -> None:
        if isinstance(node, dict):
            if "$ref" in node:
                name = _class_name(node["$ref"])
                if name not in found:
                    found.append(name)
                    visit(spec["definitions"][name])
            for value in node.values():
                visit(value)
        elif isinstance(node, list):
            for value in node:
                visit(value)

    for root in roots:
        visit(root)
    return sorted(found)


def emit_models(spec: dict, ops: list[Op]) -> str:
    sdk_ops = [op for op in ops if "sdk" in op.surfaces]
    names = _model_refs(spec, [op.returns for op in sdk_ops if op.returns])
    out = [
        HEADER,
        '"""Response models. Every field is optional so a missing or new field never breaks a call."""\n\n',
        "from __future__ import annotations\n\n",
        "# typing aliases (not `X | None`): pydantic evaluates these at runtime, and the SDK supports Python 3.9\n",
        "from typing import Any, Dict, List, Optional\n\n",
        "from pydantic import BaseModel, ConfigDict, Field\n\n\n",
        "class _Model(BaseModel):\n",
        "    model_config = ConfigDict(extra=\"allow\", populate_by_name=True, protected_namespaces=())\n\n\n",
    ]
    for name in names:
        definition = spec["definitions"][name]
        out.append(f"class {name}(_Model):\n")
        props = definition.get("properties", {})
        if not props:
            out.append("    pass\n\n\n")
            continue
        for prop_name, prop in props.items():
            py = _py_type(prop, for_input=False)
            fname = _field_name(prop_name)
            alias = f", alias={prop_name!r}" if fname != prop_name else ""
            comment = f"  # one of: {', '.join(map(str, prop['enum']))}" if "enum" in prop else ""
            out.append(f"    {fname}: Optional[{_py39(py)}] = Field(default=None{alias}){comment}\n")
        out.append("\n\n")
    out.append("\n".join(f"{n}.model_rebuild()" for n in names) + "\n")
    out.append("\n__all__ = [\n" + "".join(f"    {n!r},\n" for n in names) + "]\n")
    return "".join(out)


