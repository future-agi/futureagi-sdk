def _camel(parts: list[str]) -> str:
    return "".join(p.title().replace("_", "") for p in parts)


def _op_constant(op: Op) -> str:
    return "OP_" + op.id.upper().replace(".", "_")


def _return_annotation(op: Op, *, is_async: bool) -> tuple[str, str | None]:
    model = _class_name(op.returns["$ref"]) if op.returns and "$ref" in op.returns else None
    item = f"models.{model}" if model else _py_type(op.returns, for_input=False)
    if op.pagination:
        return (f"AsyncPager[{item}]" if is_async else f"SyncPager[{item}]"), (f"models.{model}" if model else None)
    if op.returns is None:
        return "None", None
    return item, (f"models.{model}" if model else None)


def _signature(op: Op) -> tuple[list[str], list[tuple[Param, str]]]:
    """Positional path params, then keyword-only body/query params (required first)."""
    page_params = set()
    if op.pagination:
        page_params = {op.pagination["page_param"]}  # the pager owns the page cursor; page size stays
    args = ["self"]
    path = [p for p in op.params if p.location == "path"]
    rest = [p for p in op.params if p.location != "path" and p.name not in page_params]
    rest.sort(key=lambda p: not p.required)
    named: list[tuple[Param, str]] = []
    for p in path:
        args.append(f"{_field_name(p.name)}: str")
        named.append((p, _field_name(p.name)))
    if rest:
        args.append("*")
    for p in rest:
        py = _py_type(p.schema, for_input=True)
        arg = _field_name(p.name)
        args.append(f"{arg}: {py}" if p.required else f"{arg}: {py} | None = None")
        named.append((p, arg))
    return args, named


def _method(op: Op, *, is_async: bool) -> str:
    args, named = _signature(op)
    ret, model = _return_annotation(op, is_async=is_async)
    stability = op.surfaces["sdk"]["stability"]
    lines = [f"    {'async ' if is_async and not op.pagination else ''}def {op.method_name}({', '.join(args)}) -> {ret}:\n"]
    doc = op.description + (f"\n\n        .. {stability}:: this method may change without notice." if stability == "beta" else "")
    lines.append(f'        """{doc}\n\n        {op.method} {op.path}\n        """\n')
    if stability != "stable":
        lines.append(f"        _stability({op.id!r}, {stability!r})\n")
    for location in ("path", "query") if op.pagination else ("path", "query", "body"):
        group = [(p, a) for p, a in named if p.location == location]
        if group:
            items = ", ".join(f"{p.name!r}: {a}" for p, a in group)
            lines.append(f"        {location} = {{{items}}}\n")
        else:
            lines.append(f"        {location} = None\n")
    model_arg = model or "None"
    if op.pagination:
        fn = "apaginate" if is_async else "paginate"
        lines.append(f"        return self._t.{fn}({_op_constant(op)}, path=path, query=query, model={model_arg})\n")
    else:
        prefix = "await self._t.acall" if is_async else "self._t.call"
        lines.append(f"        return {prefix}({_op_constant(op)}, path=path, query=query, body=body, model={model_arg})\n")
    return "".join(lines)


def emit_resources(ops: list[Op]) -> str:
    sdk_ops = [op for op in ops if "sdk" in op.surfaces]
    tree: dict[tuple[str, ...], list[Op]] = {}
    for op in sdk_ops:
        ns = tuple(op.namespace)
        for i in range(1, len(ns) + 1):
            tree.setdefault(ns[:i], [])
        tree[ns].append(op)

    out = [
        HEADER,
        '"""Resource classes. Names come from catalog ids, so they match the MCP tools."""\n\n',
        "from __future__ import annotations\n\n",
        "from typing import Any, Literal\n\n" if any("Literal[" in _method(op, is_async=False) for op in sdk_ops) else "from typing import Any\n\n",
        "from .._pagination import AsyncPager, SyncPager\n",
        "from .._stability import _stability\n",
        "from .._transport import AsyncTransport, Operation, SyncTransport\n",
        "from . import models\n\n",
    ]
    for op in sdk_ops:
        spec = {"id": op.id, "method": op.method, "path": op.path, "unwrap": op.unwrap, "pagination": op.pagination}
        out.append(f"{_op_constant(op)} = Operation(**{spec!r})\n")
    out.append("\n")

    for is_async in (False, True):
        prefix = "Async" if is_async else ""
        transport = "AsyncTransport" if is_async else "SyncTransport"
        for ns in sorted(tree, key=lambda ns: (-len(ns), ns)):
            cls = f"{prefix}{_camel(list(ns))}Resource"
            children = sorted(child for child in tree if len(child) == len(ns) + 1 and child[: len(ns)] == ns)
            out.append(f"\n\nclass {cls}:\n")
            out.append(f"    def __init__(self, transport: {transport}) -> None:\n")
            out.append("        self._t = transport\n")
            for child in children:
                out.append(f"        self.{child[-1]} = {prefix}{_camel(list(child))}Resource(transport)\n")
            for op in sorted(tree[ns], key=lambda o: o.method_name):
                out.append("\n" + _method(op, is_async=is_async))
        roots = sorted(ns for ns in tree if len(ns) == 1)
        out.append(f"\n\nclass {prefix}GeneratedResources:\n")
        out.append(f'    """Mixed into {prefix}Client: one attribute per top-level resource."""\n\n')
        out.append(f"    def _init_resources(self, transport: {transport}) -> None:\n")
        for ns in roots:
            out.append(f"        self.{ns[0]} = {prefix}{_camel(list(ns))}Resource(transport)\n")
    return "".join(out) + "\n"


