def _json_schema(spec: dict, schema: dict) -> dict:
    """Swagger 2.0 schema -> JSON Schema (x-nullable -> null union), refs inlined one level as objects."""
    schema = dict(schema)
    nullable = schema.pop("x-nullable", False)
    if "$ref" in schema:
        schema = {"type": "object"}
    schema.pop("title", None)
    if schema.get("type") == "array" and "items" in schema:
        schema["items"] = _json_schema(spec, schema["items"])
    if nullable and "type" in schema:
        schema["type"] = [schema["type"], "null"]
    return schema



def emit_mcp(spec: dict, ops: list[Op], contract_sha: str) -> str:
    tools = []
    for op in ops:
        if "mcp" not in op.surfaces:
            continue
        mcp = op.surfaces["mcp"]
        props, required = {}, []
        for p in op.params:
            props[p.name] = _json_schema(spec, p.schema)
            if p.description:
                props[p.name]["description"] = p.description
            if p.required:
                required.append(p.name)
        tools.append(
            {
                "name": mcp["name"],
                "description": op.description,
                "group": mcp["group"],
                "stability": mcp["stability"],
                "inputSchema": {"type": "object", "properties": props, "required": required, "additionalProperties": False},
                "annotations": {
                    "readOnlyHint": mcp["access"] == "read",
                    "destructiveHint": mcp["access"] == "destructive",
                    "idempotentHint": op.method in ("GET", "PUT", "DELETE"),
                },
                "request": {
                    "method": op.method,
                    "path": op.path,
                    "parameters": {loc: [p.name for p in op.params if p.location == loc] for loc in ("path", "query", "body")},
                },
                "response": {"unwrap": op.unwrap},
                "source": {"catalogId": op.id, "operationId": op.operation_id},
            }
        )
    manifest = {"schema_version": 1, "source_contract_sha256": contract_sha, "tool_count": len(tools), "tools": tools}
    return json.dumps(manifest, indent=2) + "\n"


# --------------------------------------------------------------------------- #


def build() -> dict[Path, str]:
    raw = CONTRACT.read_bytes()
    spec = json.loads(raw)
    catalog = yaml.safe_load(CATALOG.read_text())
    ops = load(spec, catalog)
    return {
        OUT_MODELS: emit_models(spec, ops),
        OUT_RESOURCES: emit_resources(ops),
        OUT_MCP: emit_mcp(spec, ops, hashlib.sha256(raw).hexdigest()),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="exit 1 if generated files are out of date")
    args = parser.parse_args()
    try:
        outputs = build()
    except CatalogError as exc:
        print(f"catalog error: {exc}", file=sys.stderr)
        return 2

    stale = [path for path, text in outputs.items() if not path.exists() or path.read_text() != text]
    if args.check:
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)} (run python sdkgen/generate.py)", file=sys.stderr)
        return 1 if stale else 0
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        print(f"{'updated' if path in stale else 'unchanged'}: {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
